// Command archive is the terminal front end of the media processing core. It
// generates deterministic MXF and MP4 fixtures, probes and demuxes them,
// recovers missing indexes, maps tracks in dependency order, remuxes without
// re-encoding, verifies the result and persists a resumable checkpoint.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	"archive/internal/checkpoint"
	"archive/internal/demux"
	"archive/internal/fault"
	"archive/internal/fixture"
	"archive/internal/model"
	"archive/internal/pipeline"
	"archive/internal/probe"
	"archive/internal/remux"
	"archive/internal/verify"
)

// Exit codes are part of the contract.
const (
	exitOK            = 0
	exitUnrecoverable = 1
	exitInvalid       = 2
)

func main() {
	os.Exit(run(os.Args[1:]))
}

func run(args []string) int {
	if len(args) == 0 {
		usage()
		return exitInvalid
	}
	switch args[0] {
	case "demo":
		return demo(args[1:])
	case "-h", "--help", "help":
		usage()
		return exitOK
	default:
		fmt.Fprintf(os.Stderr, "archive: unknown command %q\n", args[0])
		usage()
		return exitInvalid
	}
}

func usage() {
	fmt.Fprint(os.Stderr, `usage: archive demo [flags]

  --format FORMAT        fixture format set: mixed (default)
  --corrupt LIST         comma separated: truncate,segment,index,length
  --checkpoint PATH      checkpoint file (default /tmp/archive.ckpt)
  --out DIR              output directory (default ./demo-out)
  --interrupt            simulate an interruption and resume from the checkpoint
  --workers N            parallel track workers (default 3)
`)
}

func demo(args []string) int {
	fs := flag.NewFlagSet("demo", flag.ContinueOnError)
	format := fs.String("format", "mixed", "fixture format set")
	corrupt := fs.String("corrupt", "", "comma separated damage kinds")
	ckptPath := fs.String("checkpoint", "/tmp/archive.ckpt", "checkpoint file")
	outDir := fs.String("out", "demo-out", "output directory")
	interrupt := fs.Bool("interrupt", false, "simulate an interruption and resume")
	workers := fs.Int("workers", 3, "parallel track workers")
	if err := fs.Parse(args); err != nil {
		return exitInvalid
	}
	if *format != "mixed" {
		fmt.Fprintf(os.Stderr, "archive: unsupported format set %q\n", *format)
		return exitInvalid
	}
	kinds, err := fixture.ParseDamageKinds(*corrupt)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}
	if *workers < 1 {
		fmt.Fprintln(os.Stderr, "archive: workers must be >= 1")
		return exitInvalid
	}
	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}

	// Always regenerate the fixtures so a run is self-contained and
	// reproducible; generated bytes are a pure function of the spec.
	specs := fixture.DefaultMixed()
	set, err := fixture.Generate(*outDir, specs, kinds)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}
	manifest, err := set.Manifest()
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}
	fmt.Printf("fixtures dir=%s specs=%d damaged=%t\n", *outDir, len(specs), len(kinds) > 0)
	_ = manifest

	// Build the source list: when damage is requested, use the damaged copy
	// of each spec; otherwise the intact one.
	sources, truth, err := loadSources(set, len(kinds) > 0)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}

	start := time.Now()
	ins := make([]*pipeline.Ingested, 0, len(sources))
	for _, s := range sources {
		in, err := pipeline.Ingest(s)
		if err != nil {
			fmt.Fprintf(os.Stderr, "archive: input %s is unusable: %v\n", s.Name, err)
			return exitUnrecoverable
		}
		ins = append(ins, in)
	}
	stageMS := time.Since(start).Milliseconds()

	// Report probes and every detected fault with offset, track and range.
	for _, in := range ins {
		fmt.Printf("probe file=%s container=%s tracks=%d partitions=%d probe_ms=%d\n",
			in.Path, in.Container, len(in.File.Tracks), in.File.Partitions, stageMS)
	}
	allFaults := collectFaults(ins)
	for _, line := range pipeline.FaultLines(allFaults) {
		fmt.Println(line)
	}

	run, err := pipeline.Map(ins)
	if err != nil {
		fmt.Printf("mapping_failed: %v\n", err)
		fmt.Println("exit=2 mapping did not produce a success summary")
		return exitInvalid
	}
	printMapping(run)

	// The available track count is what recovery could actually yield.
	available := run.MappedWithPayload()
	fmt.Printf("track_count=%d mapped_count=%d available_tracks=%d\n",
		run.TrackCount(), run.MappedWithPayload(), available)

	// Verification failure or an unrecoverable input is reported before the
	// output is claimed complete.
	unrecoverable := allFaults.Unrecoverable()

	store := checkpoint.New(*ckptPath)
	prev, err := store.Load()
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}
	digests := pipeline.InputDigests(ins)
	if err := store.ValidateInputs(prev, digests); err != nil {
		// A checkpoint belongs to one exact input set. Resuming against any
		// other bytes is refused before a single payload is written.
		fmt.Printf("resume_rejected: %v\n", err)
		fmt.Println("exit=2 checkpoint does not match the current inputs")
		return exitInvalid
	}

	// Decide the starting point. A completed checkpoint is a finished job
	// and a fresh run reproduces it deterministically from scratch. An
	// interrupted checkpoint is resumed, reusing only fragments that reached
	// a verified output. Interrupt mode deliberately starts fresh so the
	// simulated interruption is real.
	state := &checkpoint.State{Inputs: digests, InputDigest: checkpoint.Digest(digests)}
	resumeFrom := prev != nil && !prev.Completed && !*interrupt
	if resumeFrom {
		state.Tracks = prev.Tracks
	}

	opts := remux.Options{
		Workers:   *workers,
		Committed: state.Committed(),
		OnCommit: func(tr remux.TrackResult, cf remux.CommittedFragment) error {
			return store.RecordCommit(state, tr, cf)
		},
	}
	// Persist the input binding before any work so a crash cannot leave a
	// checkpoint that later resumes against different inputs.
	if err := store.Save(state); err != nil {
		fmt.Fprintf(os.Stderr, "archive: checkpoint: %v\n", err)
		return exitInvalid
	}
	if resumeFrom {
		fmt.Printf("resume_from_checkpoint=true committed_tracks=%d\n", len(state.Tracks))
	}

	var out *remux.Result
	if *interrupt {
		// First leg: stop after one fragment of the first mapped track. The
		// interrupted result is deliberately not written; the checkpoint is
		// the only record of verified progress.
		if _, err = runRemux(run, opts, true); !errors.Is(err, remux.ErrInterrupted) {
			fmt.Fprintf(os.Stderr, "archive: expected an interruption, got %v\n", err)
			return exitInvalid
		}
		resumeStart := time.Now()
		opts.Committed = state.Committed()
		opts.FailTrack = ""
		out, err = runRemux(run, opts, false)
		if err != nil {
			fmt.Fprintf(os.Stderr, "archive: resume failed: %v\n", err)
			return exitUnrecoverable
		}
		fmt.Printf("resume_ms=%d reused_tracks=%d\n", time.Since(resumeStart).Milliseconds(), len(state.Committed()))
	} else {
		out, err = runRemux(run, opts, false)
		if err != nil {
			fmt.Fprintf(os.Stderr, "archive: remux failed: %v\n", err)
			return exitUnrecoverable
		}
	}

	outputPath := *outDir + "/restored.mp4"
	if err := os.WriteFile(outputPath, out.Data, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "archive: %v\n", err)
		return exitInvalid
	}

	outSrc := probe.Source{Name: "restored", Data: out.Data}
	outFile, err := probe.Probe(outSrc, model.ContainerMP4)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: output probe: %v\n", err)
		return exitInvalid
	}
	outDemux, err := demux.Demux(outSrc, outFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: output demux: %v\n", err)
		return exitInvalid
	}
	rep, err := verify.Check(selectedAsInput(run), out.Data)
	if err != nil {
		fmt.Fprintf(os.Stderr, "archive: verify: %v\n", err)
		return exitInvalid
	}
	for _, line := range pipeline.FaultLines(rep.Faults) {
		fmt.Println(line)
	}
	inDigest := pipeline.PayloadDigest(run.Selected)
	outDigest := pipeline.PayloadDigestOfResult(outDemux)
	fmt.Printf("payload_sha256=%s output_payload_sha256=%s payload_match=%t output_sha256=%s output=%s\n",
		inDigest, outDigest, inDigest == outDigest, out.SHA256, outputPath)
	fmt.Printf("verify_ok=%t fragments=%d stats=%s\n", rep.OK, out.Fragments, rep.Summary)

	state.OutputSHA256 = out.SHA256
	// The job is complete when the output verified. Input damage is a
	// separate verdict (exit 1) and does not make the checkpoint partial:
	// every recoverable fragment was written and verified.
	state.Completed = rep.OK
	for _, tr := range out.Tracks {
		p := state.ProgressFor(tr.Key, tr.Logical)
		p.Done = true
	}
	if err := store.Save(state); err != nil {
		fmt.Fprintf(os.Stderr, "archive: checkpoint: %v\n", err)
		return exitInvalid
	}
	printTruthCheck(truth, allFaults)

	switch {
	case !rep.OK:
		fmt.Println("exit=2 verification failed")
		return exitInvalid
	case unrecoverable:
		fmt.Printf("exit=1 input damaged; %d fault(s) are unrecoverable, output holds all recoverable media\n", countUnrecoverable(allFaults))
		return exitUnrecoverable
	default:
		fmt.Println("exit=0 all checks passed")
		return exitOK
	}
}

func runRemux(run *pipeline.Run, opts remux.Options, interrupt bool) (*remux.Result, error) {
	if interrupt {
		// Interrupt on the first track that actually has payload, addressing
		// it by its selected container key (the remux worker identity).
		for _, logical := range run.Map.Order {
			if td := run.Selected[logical]; td != nil && len(td.Packets) > 0 {
				opts.FailTrack = td.Key
				opts.FailAfter = 1
				break
			}
		}
	}
	return pipeline.Remux(run, opts)
}

// selectedAsInput exposes the selected payload streams in the same shape the
// verifier consumes, so the output is compared against exactly what the
// pipeline intended to write.
func selectedAsInput(run *pipeline.Run) *demux.Result {
	res := &demux.Result{}
	for _, logical := range run.Map.Order {
		if td := run.Selected[logical]; td != nil && len(td.Packets) > 0 {
			res.Tracks = append(res.Tracks, td)
		}
	}
	return res
}

func collectFaults(ins []*pipeline.Ingested) fault.List {
	var all fault.List
	for _, in := range ins {
		all = append(all, in.Faults...)
	}
	return all.Dedup()
}

func countUnrecoverable(l fault.List) int {
	n := 0
	for _, e := range l {
		if !e.Recoverable {
			n++
		}
	}
	return n
}

func printMapping(run *pipeline.Run) {
	for _, mt := range run.Map.Tracks {
		td := run.Selected[mt.Logical]
		pkts := 0
		if td != nil {
			pkts = len(td.Packets)
		}
		fmt.Printf("mapped logical=%s order=%d sources=%s packets=%d rotation=%d color=%s(%s) conflicts=%d\n",
			mt.Logical, mt.OrderKey, strings.Join(mt.Sources, "+"), pkts, mt.Rotation,
			mt.Color.Primaries.Value, mt.Color.Primaries.Source, len(mt.Color.Conflicts))
		for _, c := range mt.Color.Conflicts {
			fmt.Printf("  color_conflict field=%s value=%s source=%s kept=%s\n",
				c.Field, c.Value, c.Source, mt.Color.Primaries.Value)
		}
	}
}

// truthCheck compares reported ranges with the damage the fixture injected,
// so the demo proves the recovery report rather than asserting it.
type truthCheck struct {
	inj []fixture.Injection
}

func printTruthCheck(t *truthCheck, faults fault.List) {
	if t == nil || len(t.inj) == 0 {
		return
	}
	covered, total := 0, 0
	for _, inj := range t.inj {
		if !inj.HasRange {
			continue
		}
		total++
		for _, e := range faults {
			if !e.HasRange {
				continue
			}
			if e.StartNS <= inj.StartNS && e.EndNS >= inj.EndNS {
				covered++
				break
			}
		}
	}
	fmt.Printf("injected_ranges=%d covered_ranges=%d\n", total, covered)
	if total != covered {
		fmt.Println("warning: some injected ranges were not reported")
	}
}

func loadSources(set *fixture.Set, damaged bool) ([]pipeline.Source, *truthCheck, error) {
	var sources []pipeline.Source
	truth := &truthCheck{}
	for _, spec := range fixture.DefaultMixed() {
		art := set.Clean(spec.Name)
		if damaged {
			if d := set.Damaged(spec.Name); d != nil {
				art = d
				truth.inj = append(truth.inj, d.Injections...)
			}
		}
		if art == nil {
			return nil, nil, fmt.Errorf("fixture %s missing", spec.Name)
		}
		data, err := os.ReadFile(art.Path)
		if err != nil {
			return nil, nil, err
		}
		sources = append(sources, pipeline.Source{
			Name:   spec.Name,
			Format: model.ContainerKind(art.Format),
			Data:   data,
		})
	}
	return sources, truth, nil
}
