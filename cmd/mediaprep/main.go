func main() {
	os.Exit(run(os.Args[1:]))
}

func run(args []string) int {
	if len(args) == 0 {
		fmt.Fprintln(os.Stderr, "usage: mediaprep <demo|verify|migrate> [flags]")
		return 1
	}
	switch args[0] {
	case "demo":
		return runDemo(args[1:])
	case "verify":
		return runVerify(args[1:])
	case "migrate":
		return runMigrate(args[1:])
	case "inspect":
		return runInspect(args[1:])
	case "-h", "--help", "help":
		fmt.Println("usage: mediaprep <demo|verify|migrate|inspect> [flags]")
		return 0
	default:
		fmt.Fprintf(os.Stderr, "unknown command %q\n", args[0])
		return 1
	}
}

func runDemo(args []string) int {
	fs := flag.NewFlagSet("demo", flag.ContinueOnError)
	root := fs.String("root", "", "demo root directory")
	generate := fs.Bool("generate", false, "generate code-defined fixtures")
	queue := fs.Int("queue", 2, "bounded queue capacity")
	budget := fs.Int64("budget-bytes", 262144, "maximum buffered block bytes")
	slowMS := fs.Int("slow-consumer-ms", 0, "simulated consumer delay per block")
	if err := fs.Parse(args); err != nil {
		return 1
	}

	doc, err := app.RunDemo(context.Background(), app.DemoOptions{
		Root: *root, Generate: *generate, Queue: *queue,
		BudgetBytes: *budget, SlowConsumerMS: *slowMS,
	})
	if err != nil {
		printError(err)
		return model.InputExitCode(err)
	}

	s := doc.Summary
	fmt.Printf("root=%s\n", doc.Root)
	fmt.Printf("segments=%d\n", s.Segments)
	fmt.Printf("silent=%d\n", s.Silent)
	fmt.Printf("duplicates=%d\n", s.Duplicates)
	fmt.Printf("metadata_conflicts=%d\n", s.MetadataConflicts)
	fmt.Printf("queue_peak=%d\n", s.QueuePeak)
	fmt.Printf("queue_capacity=%d\n", s.QueueCapacity)
	fmt.Printf("queue_peak_requirement=%d<=%d\n", s.QueuePeak, *queue)
	fmt.Printf("buffer_peak_bytes=%d\n", s.BufferPeakBytes)
	fmt.Printf("buffer_budget_bytes=%d\n", s.BufferBudgetBytes)
	fmt.Printf("buffer_actual_bytes=%d\n", doc.Pipeline.BufferActualBytes)
	fmt.Printf("buffer_peak_requirement=%d<=%d\n", s.BufferPeakBytes, s.BufferBudgetBytes)
	fmt.Printf("blocks_produced=%d blocks_consumed=%d residual_tasks=%d\n",
		doc.Pipeline.BlocksProduced, doc.Pipeline.BlocksConsumed, doc.Pipeline.ResidualTasks)
	fmt.Printf("verdict=%s\n", s.Verdict)

	for i, seg := range doc.Segments {
		fmt.Printf("segment[%d] id=%s track=%s interval=[%d,%d) scale=%s bytes=%d samples=[%d,%d)\n",
			i+1, seg.ID, seg.Track, seg.Interval.Start, seg.Interval.End,
			seg.Interval.Scale.String(), seg.ByteSize, seg.FirstSample, seg.EndSample)
	}
	for i, ex := range doc.Exceptions {
		fmt.Printf("exception[%d] kind=%s phase=%s", i+1, ex.Kind, ex.Phase)
		if ex.Track != "" {
			fmt.Printf(" track=%s", ex.Track)
		}
		if ex.HasOffset {
			fmt.Printf(" source_offset=%d", ex.Offset)
		}
		if ex.Interval != nil {
			fmt.Printf(" interval=[%d,%d) scale=%s duration_ms=%.3f",
				ex.Interval.Start, ex.Interval.End, ex.Interval.Scale.String(),
				intervalMS(*ex.Interval))
		} else {
			fmt.Print(" interval=-")
		}
		fmt.Printf("\n  issue: %s\n", ex.Message)
		fmt.Printf("  conclusion: %s\n", ex.Resolution)
	}
	if s.Verdict != "PASS" {
		return 1
	}
	return 0
}

func runVerify(args []string) int {
	fs := flag.NewFlagSet("verify", flag.ContinueOnError)
	root := fs.String("root", "", "verification fixture root (default temp dir)")
	generate := fs.Bool("generate", false, "generate code-defined boundary fixtures")
	casesFlag := fs.String("cases", strings.Join(app.AllVerifyCases, ","), "comma-separated cases")
	if err := fs.Parse(args); err != nil {
		return 1
	}
	_ = generate // verification fixtures are always generated by this local command.
	var cases []string
	for _, c := range strings.Split(*casesFlag, ",") {
		if c = strings.TrimSpace(c); c != "" {
			cases = append(cases, c)
		}
	}
	results, err := app.RunVerifyCases(context.Background(), *root, cases)
	for i, r := range results {
		fmt.Printf("case[%d]=%s conclusion=%s accepted=%t", i+1, r.Name, r.Conclusion, r.Accepted)
		if r.Track != "" {
			fmt.Printf(" track=%s", r.Track)
		}
		if r.HasOffset {
			fmt.Printf(" offset=%d", r.Offset)
		}
		if r.ResidualTasks != 0 || r.Name == "cancel" {
			fmt.Printf(" residual_tasks=%d", r.ResidualTasks)
		}
		fmt.Printf("\n  %s\n", r.Detail)
	}
	if err != nil {
		fmt.Printf("verify_verdict=FAIL\n")
		printError(err)
		return model.InputExitCode(err)
	}
	fmt.Println("verify_verdict=PASS")
	return 0
}

func runMigrate(args []string) int {
	fs := flag.NewFlagSet("migrate", flag.ContinueOnError)
	root := fs.String("root", "", "demo/manifest root")
	from := fs.String("from", "", "source version, e.g. v1")
	stopAfter := fs.String("stop-after", "", "set to prepare to inject an interruption after prepare")
	resume := fs.Bool("resume", false, "resume a prepared migration and commit atomically")
	rollback := fs.Bool("rollback", false, "restore the preserved old pointer")
	if err := fs.Parse(args); err != nil {
		return 1
	}
	if *root == "" {
		fmt.Fprintln(os.Stderr, "--root is required")
		return 1
	}

	switch {
	case *resume:
		res, err := migrate.Resume(*root, time.Now())
		if err != nil {
			printError(err)
			return model.InputExitCode(err)
		}
		fmt.Printf("migration=resume current=%s pointer_sha256=%s\n", res.Pointer.Version, res.PointerSHA256)
		fmt.Printf("v2_manifest_sha256=%s\n", res.Pointer.SHA256)
		fmt.Printf("rollback=v1 path=%s available=true\n", res.RollbackPath)
		return 0
	case *rollback:
		res, err := migrate.Rollback(*root, time.Now())
		if err != nil {
			printError(err)
			return model.InputExitCode(err)
		}
		fmt.Printf("rollback_complete current=%s pointer_sha256=%s\n", res.Pointer.Version, res.PointerSHA256)
		return 0
	default:
		stop := *stopAfter == "prepare"
		plan, err := migrate.Prepare(*root, *from, stop, time.Now())
		if plan != nil {
			fmt.Printf("migration=prepare from=%s to=%s\n", plan.From, plan.To)
			fmt.Printf("v1_manifest_sha256=%s\n", plan.V1SHA256)
			fmt.Printf("v2_manifest_sha256=%s\n", plan.V2SHA256)
			fmt.Printf("v1_pointer_sha256=%s current_pointer_unchanged=true\n", plan.PointerSHA256AtPrepare)
		}
		if err != nil {
			if stop && (errors.Is(err, model.ErrMigrationStopped) || model.InputExitCode(err) == 3) {
				fmt.Println("migration=interrupted phase=prepare; current version pointer was not switched")
				return 3
			}
			printError(err)
			return model.InputExitCode(err)
		}
		if plan != nil && plan.Committed {
			fmt.Println("migration=committed current=v2 atomic_switch=true rollback=v1")
		} else {
			fmt.Println("migration=prepared; run --resume to atomically switch current pointer")
		}
		return 0
	}
}

func printError(err error) {
	if pe, ok := model.AsError(err); ok {
		fmt.Fprintf(os.Stderr, "error code=%s phase=%s", pe.Code, pe.Phase)
		if pe.Track != "" {
			fmt.Fprintf(os.Stderr, " track=%s", pe.Track)
		}
		if pe.HasOffset {
			fmt.Fprintf(os.Stderr, " offset=%d", pe.Offset)
		}
		fmt.Fprintf(os.Stderr, ": %s", pe.Message)
		if pe.Err != nil {
			fmt.Fprintf(os.Stderr, ": %v", pe.Err)
		}
		fmt.Fprintln(os.Stderr)
		return
	}
	fmt.Fprintf(os.Stderr, "error: %v\n", err)
}

func intervalMS(in model.Interval) float64 {
	if in.Scale.Denominator == 0 {
		return 0
	}
	return float64(in.End-in.Start) * float64(in.Scale.Numerator) /
		float64(in.Scale.Denominator) * 1000
}
