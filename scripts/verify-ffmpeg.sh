#!/usr/bin/env bash
# verify-ffmpeg.sh - external cross-check using the FFmpeg CLI.
#
# The Go test suite generates synthetic, structurally-valid MP4 fixtures whose
# media payload is placeholder bytes (the library repairs timestamps and index
# structure, it does not transcode). This script complements it with a real,
# decodable stream produced and measured entirely by FFmpeg:
#
#   1. generate a short test source and encode it to H.264 in MP4
#   2. probe the container to confirm a parseable sample table and timescale
#   3. decode against the synthetic source with the psnr filter to prove the
#      round trip stays above the 35 dB acceptance floor
#
# It is intentionally optional: `go test ./...` has no external dependency.
set -euo pipefail

WORK="${1:-./tmp/ffmpeg}"
mkdir -p "$WORK"
SRC="$WORK/source.yuv"
ENC="$WORK/encoded.mp4"
DEC="$WORK/decoded.yuv"

# 32 frames at 320x240, 25 fps, raw I420 generated by the lavfi testsrc source.
W=320
H=240
FRAMES=32
FPS=25

if ! command -v ffmpeg >/dev/null 2>&1; then
	echo "ffmpeg not found on PATH; skipping external verification" >&2
	exit 0
fi

echo "== generating raw source =="
ffmpeg -hide_banner -loglevel error -y \
	-f lavfi -i "testsrc=size=${W}x${H}:rate=${FPS}:duration=$(awk "BEGIN{print $FRAMES/$FPS}")" \
	-pix_fmt yuv420p -frames:v "$FRAMES" "$SRC"

echo "== encoding to H.264 MP4 =="
ffmpeg -hide_banner -loglevel error -y \
	-f rawvideo -pix_fmt yuv420p -s "${W}x${H}" -r "$FPS" -i "$SRC" \
	-c:v libx264 -preset veryfast -pix_fmt yuv420p -movflags +faststart "$ENC"

echo "== probing container =="
# -count_packets makes nb_read_packets available; supported across FFmpeg 7/9.
ffprobe -hide_banner -loglevel error -v error \
	-select_streams v:0 -count_packets \
	-show_entries stream=codec_name,nb_read_packets,time_base \
	-of default=noprint_wrappers=1 "$ENC"

echo "== decoding and computing PSNR =="
ffmpeg -hide_banner -loglevel info -y \
	-f rawvideo -pix_fmt yuv420p -s "${W}x${H}" -r "$FPS" -i "$SRC" \
	-i "$ENC" -lavfi psnr -f null - 2> "$WORK/psnr.log"
grep -E "PSNR" "$WORK/psnr.log" | tail -3

echo "FFmpeg verification artifacts written under $WORK"
