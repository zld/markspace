"""Deterministic WAV fixture generation for tests and demos.

Everything is generated by code from fixed seeds; no external audio is used.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

SEED = 20240217


def sine(rate: int, frames: int, freq: float, amp: float, channels: int = 1) -> np.ndarray:
    t = np.arange(frames, dtype=np.float64) / float(rate)
    wave = amp * np.sin(2.0 * math.pi * freq * t)
    return np.repeat(wave[:, None], channels, axis=1)


def stereo_interleaved(rate: int, frames: int) -> np.ndarray:
    """Distinct left/right content so channel swaps are detectable."""
    t = np.arange(frames, dtype=np.float64) / float(rate)
    left = 0.35 * np.sin(2.0 * math.pi * 440.0 * t)
    right = 0.25 * np.sin(2.0 * math.pi * 660.0 * t) + 0.05 * np.sin(2.0 * math.pi * 120.0 * t)
    return np.column_stack((left, right))


def noise(rate: int, frames: int, channels: int, scale: float) -> np.ndarray:
    rng = np.random.default_rng(SEED)
    return rng.normal(0.0, scale, (frames, channels))


def write(path: Path, data: np.ndarray, rate: int, subtype: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(path), data, rate, subtype=subtype, format="WAV")


def make_fixtures(out: Path) -> list[Path]:
    """Create the valid fixture set; returns the written paths."""
    written: list[Path] = []

    def emit(name: str, data: np.ndarray, rate: int, subtype: str = "PCM_16") -> None:
        target = out / name
        write(target, data, rate, subtype)
        written.append(target)

    emit("stereo_44100.wav", stereo_interleaved(44100, 44100), 44100)
    emit("stereo_48000.wav", stereo_interleaved(48000, 30017), 48000, "PCM_24")
    emit("mono_22050.wav", sine(22050, 22050, 300.0, 0.4), 22050)
    emit("mono_96000.wav", sine(96000, 96000, 880.0, 0.2), 96000, "PCM_24")
    emit("silence_44100.wav", np.zeros((44100, 2)), 44100)
    emit("full_scale_sine.wav", sine(48000, 48000, 1000.0, 1.0, channels=2), 48000)
    # Full-scale square wave: resampler overshoot makes the pre-gain peak
    # exceed 0 dBFS, which exercises the clipping counters.
    square = np.sign(sine(48000, 24000, 250.0, 1.0, channels=1)[:, 0])
    emit("square_48000.wav", square[:, None], 48000, "PCM_16")
    # 333 frames: tail shorter than one processing block and the kernel.
    emit("short_tail.wav", noise(32000, 333, 2, 0.08), 32000, "PCM_24")
    emit("one_frame.wav", np.array([[0.5]]), 44100)
    emit("empty.wav", np.zeros((0, 1)), 44100)
    # 8-channel interleaved ramps; each channel has a distinct offset.
    frames = 1234
    ramp = np.arange(frames, dtype=np.float64) / frames
    multi = np.column_stack([np.clip(ramp - 0.05 * ch, 0.0, 1.0) for ch in range(8)])
    emit("multi_8ch_44100.wav", multi, 44100, "PCM_24")
    # Non-integer ratios: 44100 -> 48000 keeps duration, 32000 -> 44100 upsamples.
    # The right channel is quieter so channel swaps show up in the output.
    emit(
        "sweep_44100.wav",
        np.column_stack(
            (
                sine(44100, 4410, 1000.0, 0.5)[:, 0],
                sine(44100, 4410, 1500.0, 0.3)[:, 0],
            )
        ),
        44100,
    )
    emit("tone_32000.wav", sine(32000, 3200, 250.0, 0.3), 32000, "PCM_24")
    # Extension case is irrelevant to discovery.
    emit("UPPER_CASE.WAV", sine(16000, 16000, 250.0, 0.3), 16000)
    # Nested tree exercises recursive scanning and relative-path reporting.
    emit("nested/deep/tone_48000.wav", sine(48000, 4800, 500.0, 0.25), 48000)
    return written


def invalid_fixtures(out: Path) -> list[Path]:
    """Files that must be rejected; kept out of the main fixture directory."""
    written: list[Path] = []
    out.mkdir(parents=True, exist_ok=True)
    # Truncated payload behind a plausible header.
    truncated = out / "corrupt.wav"
    truncated.write_bytes(
        b"RIFF\x24\x00\x00\x00WAVEfmt \x10\x00\x00\x00\x01\x00\x01\x00"
        b"\x44\xac\x00\x00\x88\x58\x01\x00\x02\x00\x10\x00data\x00\x04\x00\x00"
    )
    written.append(truncated)
    # Not a WAV at all.
    garbage = out / "garbage.wav"
    garbage.write_bytes(b"RIFF\x10\x00\x00\x00WAVEjunk" + bytes(range(64)))
    written.append(garbage)
    # Non-PCM encoding: IEEE float must be refused by the PCM-only policy.
    float_path = out / "float_encoding.wav"
    write(float_path, sine(32000, 512, 500.0, 0.1), 32000, "FLOAT")
    written.append(float_path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate deterministic WAV fixtures")
    parser.add_argument("--out", required=True, help="output directory")
    parser.add_argument(
        "--with-invalid",
        action="store_true",
        help="also write rejectable fixtures to <out>-invalid",
    )
    args = parser.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    paths = make_fixtures(out)
    for path in paths:
        print(f"wrote {path}")
    if args.with_invalid:
        for path in invalid_fixtures(out.parent / f"{out.name}-invalid"):
            print(f"wrote {path} (expected reject)")
    print(f"{len(paths)} fixtures in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
