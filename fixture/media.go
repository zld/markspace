package fixture

import (
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"math/rand"
)

// Box builds a correctly sized ISO-BMFF box for self-generated fMP4 fixtures.
func Box(typ string, payload []byte) []byte {
	if len(typ) != 4 {
		panic("box type must be four characters")
	}
	b := make([]byte, 8+len(payload))
	binary.BigEndian.PutUint32(b[:4], uint32(len(b)))
	copy(b[4:8], typ)
	copy(b[8:], payload)
	return b
}

// Fragment builds a small structurally parseable fMP4 fragment.
func Fragment(seed int64, index int, size int) []byte {
	if size < 64 {
		size = 64
	}
	r := rand.New(rand.NewSource(seed + int64(index)*1009))
	payload := make([]byte, size)
	_, _ = r.Read(payload)

	ftypPayload := make([]byte, 16)
	copy(ftypPayload[0:4], "iso5")
	binary.BigEndian.PutUint32(ftypPayload[4:8], 0x00000200)
	copy(ftypPayload[8:12], "iso5")
	copy(ftypPayload[12:16], "mp41")
	ftyp := Box("ftyp", ftypPayload)

	mfhd := make([]byte, 8)
	binary.BigEndian.PutUint32(mfhd[4:8], uint32(index+1))

	tfhd := make([]byte, 8)
	binary.BigEndian.PutUint32(tfhd[4:8], 1) // track ID
	tfdt := make([]byte, 8)
	binary.BigEndian.PutUint32(tfdt[4:8], uint32(index*2000))
	traf := Box("traf", append(Box("tfhd", tfhd), Box("tfdt", tfdt)...))
	moof := Box("moof", append(Box("mfhd", mfhd), traf...))
	mdat := Box("mdat", payload)

	out := make([]byte, 0, len(ftyp)+len(moof)+len(mdat))
	out = append(out, ftyp...)
	out = append(out, moof...)
	out = append(out, mdat...)
	return out
}

// Truncate returns a prefix that leaves a box header claiming more bytes than
// remain. The cutoff is chosen inside the final mdat payload.
func Truncate(b []byte) []byte {
	if len(b) < 24 {
		return b[:len(b)/2]
	}
	return b[:len(b)-len(b)/3]
}

// Corrupt flips bytes near the moof payload without changing its outer size.
func Corrupt(b []byte, seed int64) []byte {
	out := append([]byte(nil), b...)
	r := rand.New(rand.NewSource(seed + 777))
	for i := 0; i < 8; i++ {
		at := 16 + r.Intn(max(1, len(out)-32))
		out[at] ^= 0xff
	}
	// The first top-level box is always the 24-byte ftyp. Inflate the moof
	// size so go-mp4 rejects the damaged DASH bytes deterministically.
	if len(out) > 28 {
		binary.BigEndian.PutUint32(out[24:28], 0xfffffff0)
	}
	return out
}

func max(a, b int) int {
	if a > b {
		return a
	}
	return b
}

// MustDigest is a test/fixture helper that never fails for generated bytes.
func MustDigest(data []byte) string {
	sum := sha256.Sum256(data)
	return fmt.Sprintf("%x", sum[:])
}
