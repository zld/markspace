package samplegen

import (
	"encoding/binary"

	"github.com/zld/mediacore/internal/model"
)

// Fixture timing constants.
const (
	StepNS          = model.NS(100_000_000)
	VideoTimescale  = 90_000
	VideoStepTicks  = 9_000
	AudioTimescale  = 48_000
	AudioStepTicks  = 4_800
	AudioFramesStep = 4_800
)

// NormalSpec returns the five-second? No: one-second three-track fixture.
// Track 2 is a delayed alternate source and carries the same content for the
// global steps it shares with track 1.
func NormalSpec(includeIndex bool) Spec {
	track1 := TrackSpec{ID: 1, Kind: "video", TimeScale: VideoTimescale}
	for i := 0; i < 6; i++ {
		track1.Samples = append(track1.Samples, SampleSpec{
			Index: i, StartTick: uint64(i * VideoStepTicks), DurationTick: VideoStepTicks,
			Payload: videoPayload(i),
		})
	}

	track2 := TrackSpec{ID: 2, Kind: "video", TimeScale: VideoTimescale, OffsetNS: 4 * StepNS}
	for local := 0; local < 6; local++ {
		globalStep := local + 4
		track2.Samples = append(track2.Samples, SampleSpec{
			Index: local, StartTick: uint64(local * VideoStepTicks), DurationTick: VideoStepTicks,
			Payload: videoPayload(globalStep),
		})
	}

	track3 := TrackSpec{ID: 3, Kind: "audio", TimeScale: AudioTimescale}
	for i := 0; i < 10; i++ {
		track3.Samples = append(track3.Samples, SampleSpec{
			Index: i, StartTick: uint64(i * AudioStepTicks), DurationTick: AudioStepTicks,
			Payload: audioPayload(i),
		})
	}

	return Spec{IncludeIndex: includeIndex, Tracks: []TrackSpec{track1, track2, track3}}
}

func videoPayload(globalStep int) []byte {
	b := make([]byte, 64)
	copy(b[0:8], []byte("MCSVID01"))
	binary.BigEndian.PutUint64(b[8:16], uint64(globalStep))
	for i := 16; i < len(b); i++ {
		b[i] = byte(globalStep*31 + i*7)
	}
	return b
}

func audioPayload(step int) []byte {
	b := make([]byte, AudioFramesStep*2)
	if step == 3 || step == 4 {
		return b // exact digital silence on [300ms, 500ms)
	}
	for frame := 0; frame < AudioFramesStep; frame++ {
		v := int16(12_000)
		if (frame/240)%2 == 1 {
			v = -12_000
		}
		binary.LittleEndian.PutUint16(b[frame*2:frame*2+2], uint16(v))
	}
	return b
}

// TruncateInSample truncates generated bytes inside one sample payload and
// returns the absolute EOF/corruption offset.
func TruncateInSample(g *Generated, trackID, index, payloadByte int) (int64, bool) {
	loc, ok := g.Location(trackID, index)
	if !ok {
		return 0, false
	}
	offset := loc.DataStart + int64(payloadByte)
	if offset >= int64(len(g.Data)) || payloadByte < 0 {
		return 0, false
	}
	g.Data = g.Data[:offset]
	return offset, true
}

// CorruptBoxLength replaces a box length with an impossible sub-header size.
// It returns the box start, which is the first corrupted length byte.
func CorruptBoxLength(g *Generated, trackID, index int) (int64, bool) {
	loc, ok := g.Location(trackID, index)
	if !ok || loc.BoxOffset+4 > int64(len(g.Data)) {
		return 0, false
	}
	binary.BigEndian.PutUint32(g.Data[loc.BoxOffset:loc.BoxOffset+4], 4)
	return loc.BoxOffset, true
}

// FlipFirstPayloadByte corrupts the first media byte without changing boxes.
func FlipFirstPayloadByte(g *Generated, trackID, index int) (int64, bool) {
	loc, ok := g.Location(trackID, index)
	if !ok || loc.DataStart >= int64(len(g.Data)) {
		return 0, false
	}
	g.Data[loc.DataStart] ^= 0xFF
	return loc.DataStart, true
}
