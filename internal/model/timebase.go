// Package model defines the shared time base, numeric helpers and the
// structured error model used by every stage of the offline RTP/WAV
// processing pipeline.
package model

import "fmt"

// RTPWrap is the 32-bit RTP timestamp modulus (RFC 3550).
const RTPWrap uint64 = 1 << 32

// Limits describes the bounded-memory caps a parser must enforce. Zero
// values select the package defaults.
type Limits struct {
	MaxPackets int // maximum accepted RTP packets
	MaxBlocks  int // maximum accepted WAV sample blocks
	MaxBytes   int // maximum accepted input size in bytes
}

// DefaultLimits returns conservative caps suitable for offline regression
// traces generated by this project.
func DefaultLimits() Limits {
	return Limits{MaxPackets: 200_000, MaxBlocks: 200_000, MaxBytes: 256 << 20}
}

// Range is a half-open byte or index interval [Start, End).
type Range struct {
	Start int64 `json:"start"`
	End   int64 `json:"end"`
}

// String renders the half-open interval.
func (r Range) String() string { return fmt.Sprintf("[%d,%d)", r.Start, r.End) }

// Overlaps reports whether two half-open ranges share any element.
func (r Range) Overlaps(o Range) bool {
	return r.Start < o.End && o.Start < r.End
}

// Merge returns the smallest range covering both inputs.
func (r Range) Merge(o Range) Range {
	if o.Start < r.Start {
		r.Start = o.Start
	}
	if o.End > r.End {
		r.End = o.End
	}
	return r
}

// SamplesToNS converts a sample count at sampleRate to nanoseconds.
func SamplesToNS(samples, sampleRate uint64) int64 {
	return int64(samples * 1_000_000_000 / sampleRate)
}

// NSToSamples converts nanoseconds to a sample count at sampleRate,
// rounding to the nearest sample.
func NSToSamples(ns int64, sampleRate uint64) uint64 {
	if ns < 0 {
		ns = 0
	}
	return uint64((uint64(ns)*sampleRate + 500_000_000) / 1_000_000_000)
}

// RTPToNS converts RTP clock ticks (already unwrapped) to nanoseconds.
func RTPToNS(ticks, clockRate uint64) int64 {
	return int64(ticks * 1_000_000_000 / clockRate)
}

// NSToRTP converts nanoseconds to RTP clock ticks, rounding to the
// nearest tick.
func NSToRTP(ns int64, clockRate uint64) uint64 {
	if ns < 0 {
		ns = 0
	}
	return (uint64(ns)*clockRate + 500_000_000) / 1_000_000_000
}

// WrapDiff returns the signed forward distance from a to b on the 32-bit
// RTP timestamp ring. A negative result means b is behind a.
func WrapDiff(a, b uint32) int64 {
	d := int64(uint32(b - a))
	if d > int64(RTPWrap/2) {
		d -= int64(RTPWrap)
	}
	return d
}
