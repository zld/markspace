// Package mxfschema defines the universal labels and local-set tags of the
// bounded MXF regression profile shared by the fixture writer and the parser.
//
// The profile is deliberately small: one closed header partition carrying a
// Preface, one or more descriptors and one index, followed by essence KLVs.
// The partition, preface and essence keys follow SMPTE 377M/379M style; the
// descriptor and index labels are private so no real-world file is
// misidentified as this profile.
package mxfschema

// UL is a 16-byte SMPTE universal label.
type UL [16]byte

// Keys of the regression profile.
var (
	HeaderPartition = UL{0x06, 0x0e, 0x2b, 0x34, 0x02, 0x05, 0x01, 0x01, 0x0d, 0x01, 0x02, 0x01, 0x01, 0x02, 0x04, 0x00}
	Preface         = UL{0x06, 0x0e, 0x2b, 0x34, 0x02, 0x53, 0x01, 0x01, 0x0d, 0x01, 0x01, 0x01, 0x01, 0x01, 0x2f, 0x00}
	Descriptor      = UL{0x06, 0x0e, 0x2b, 0x34, 0x02, 0x01, 0x01, 0x01, 0x0d, 0x01, 0x03, 0x01, 0x7f, 0x01, 0x01, 0x00}
	Index           = UL{0x06, 0x0e, 0x2b, 0x34, 0x02, 0x01, 0x01, 0x01, 0x0d, 0x01, 0x03, 0x01, 0x7f, 0x01, 0x02, 0x00}
	VideoEssence    = UL{0x06, 0x0e, 0x2b, 0x34, 0x01, 0x02, 0x03, 0x01, 0x0d, 0x01, 0x03, 0x01, 0x15, 0x01, 0x01, 0x00}
	AudioEssence    = UL{0x06, 0x0e, 0x2b, 0x34, 0x01, 0x02, 0x03, 0x01, 0x0d, 0x01, 0x03, 0x01, 0x15, 0x01, 0x02, 0x00}
)

// Partition-pack tags.
const (
	TagMajorVersion   = 0x0201
	TagMinorVersion   = 0x0202
	TagKAGSize        = 0x0203
	TagPartitionSize  = 0x0204
	TagThisPartition  = 0x0205
	TagPrevPartition  = 0x0206
	TagThisNumber     = 0x0207
	TagBodyOffset     = 0x0208
	TagBodyBodyOffset = 0x0209
)

// Descriptor local-set tags.
const (
	TagSetVersion  = 0x0100
	TagPriority    = 0x0101
	TagTrackID     = 0x3006
	TagTrackKind   = 0x3005
	TagTimescale   = 0x3007
	TagDuration    = 0x3008
	TagWidth       = 0x3201
	TagHeight      = 0x3202
	TagRotation    = 0x3211
	TagCropWidth   = 0x3220
	TagCropHeight  = 0x3221
	TagCropX       = 0x3222
	TagCropY       = 0x3223
	TagPrimaries   = 0x3230
	TagTransfer    = 0x3231
	TagMatrix      = 0x3232
	TagFullRange   = 0x3233
	TagAudioRate   = 0x3d09
	TagAudioChan   = 0x3d07
	TagAudioLayout = 0x3d0a
)

// Index local-set tags.
const (
	TagBlockCount = 0x0201
	TagBlock      = 0x0202
	TagBlockNo    = 0x0203
	TagStartFrame = 0x0204
	TagFrames     = 0x0205
	TagPayloadOff = 0x0206
	TagPayloadLen = 0x0207
	TagPayloadCRC = 0x0208
)
