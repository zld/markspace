// Package metrics numerically checks the delivered manifest against the
// rewritten media file. All rates and alignment errors derive from media time.
package metrics

import (
	"math"
	"path/filepath"

	"mediapack/internal/clock"
	"mediapack/internal/demux"
	"mediapack/internal/fault"
	"mediapack/internal/index"
	"mediapack/internal/pathsafe"
)

type Report struct {
	Tracks                   int     `json:"tracks"`
	Samples                  int     `json:"samples"`
	PayloadHashMismatches    int     `json:"payload_hash_mismatches"`
	TargetBitrateBps         float64 `json:"target_bitrate_bps"`
	ActualBitrateBps         float64 `json:"actual_bitrate_bps"`
	BitrateDeviationPct      float64 `json:"bitrate_deviation_pct"`
	QualityDroppedSamples    int     `json:"quality_dropped_samples"`
	ManifestAlignmentErrorMS float64 `json:"manifest_alignment_error_ms"`
	RecoveredChunks          int     `json:"recovered_chunks"`
}

// VerifyDirectory loads manifest.json and independently demuxes output.mp4.
func VerifyDirectory(dir string) (*Report, *index.Manifest, error) {
	manifestPath, err := pathsafe.Join(dir, "manifest.json")
	if err != nil {
		return nil, nil, err
	}
	var m index.Manifest
	if err := index.LoadJSON(manifestPath, &m); err != nil {
		return nil, nil, fault.Wrap(fault.KindVerify, err)
	}
	outName := m.OutputMP4
	if outName == "" {
		outName = "output.mp4"
	}
	outPath, err := resolveManifestMedia(dir, outName)
	if err != nil {
		return nil, &m, err
	}
	doc, err := demux.DemuxMP4(outPath)
	if err != nil {
		return nil, &m, err
	}

	r := &Report{
		Tracks:                len(m.Tracks),
		Samples:               m.SampleCount,
		TargetBitrateBps:      m.TargetBitrateBps,
		QualityDroppedSamples: m.QualityDroppedSamples,
		RecoveredChunks:       m.RecoveredChunks,
	}
	var totalPayloadBytes int64
	var maxDurationSec float64
	var maxAlignmentMS float64

	for _, mt := range m.Tracks {
		ot := doc.Track(mt.TargetID)
		if ot == nil {
			r.PayloadHashMismatches += mt.SampleCount
			continue
		}
		expected := mt.SampleHashes
		for i, s := range ot.Samples {
			totalPayloadBytes += int64(s.Size)
			if i >= len(expected) || expected[i] != s.Hash {
				r.PayloadHashMismatches++
			}
		}
		if len(ot.Samples) < len(expected) {
			r.PayloadHashMismatches += len(expected) - len(ot.Samples)
		}
		dur := trackDurationSeconds(ot)
		if dur > maxDurationSec {
			maxDurationSec = dur
		}
		if mt.DurationSeconds > 0 {
			if ms := math.Abs(mt.DurationSeconds-dur) * 1000; ms > maxAlignmentMS {
				maxAlignmentMS = ms
			}
		}
	}
	r.ActualBitrateBps = BitrateBps(totalPayloadBytes, maxDurationSec)
	if r.TargetBitrateBps > 0 {
		r.BitrateDeviationPct = math.Abs(r.TargetBitrateBps-r.ActualBitrateBps) / r.TargetBitrateBps * 100
	}
	r.ManifestAlignmentErrorMS = maxAlignmentMS
	m.ActualBitrateBps = r.ActualBitrateBps
	m.BitrateDeviationPct = r.BitrateDeviationPct
	m.ManifestAlignmentErrorMS = r.ManifestAlignmentErrorMS
	m.PayloadHashMismatches = r.PayloadHashMismatches

	if err := ThresholdError(r); err != nil {
		return r, &m, err
	}
	return r, &m, nil
}

func BitrateBps(payloadBytes int64, durationSeconds float64) float64 {
	if durationSeconds <= 0 {
		return 0
	}
	return float64(payloadBytes) * 8 / durationSeconds
}

func ThresholdError(r *Report) error {
	if r.PayloadHashMismatches != 0 {
		return fault.New(fault.KindVerify, "payload hash mismatches: %d", r.PayloadHashMismatches)
	}
	if r.QualityDroppedSamples != 0 {
		return fault.New(fault.KindVerify, "quality dropped samples: %d", r.QualityDroppedSamples)
	}
	if r.ManifestAlignmentErrorMS > 1.0 {
		return fault.New(fault.KindVerify, "alignment error %.3f ms > 1 ms", r.ManifestAlignmentErrorMS)
	}
	if r.TargetBitrateBps > 0 && r.BitrateDeviationPct > 5.0 {
		return fault.New(fault.KindVerify, "bitrate deviation %.2f%% > 5%%", r.BitrateDeviationPct)
	}
	return nil
}

func trackDurationSeconds(t *demux.Track) float64 {
	if len(t.Samples) == 0 {
		return 0
	}
	last := t.Samples[len(t.Samples)-1]
	end := clock.Ticks(last.DTS+last.Duration, t.Timebase)
	return end.Float64()
}

func resolveManifestMedia(dir, name string) (string, error) {
	if filepath.IsAbs(name) {
		// Manifests generated by this tool store a base name. Accept an absolute
		// path only when it is already the exact file inside dir.
		rel, err := filepath.Rel(dir, name)
		if err != nil || rel == ".." || filepath.IsAbs(rel) || len(rel) >= 3 && rel[:3] == ".."+string(filepath.Separator) {
			return "", fault.AtPosition(fault.KindPath, name, "media path escapes verification directory")
		}
		return name, nil
	}
	return pathsafe.Join(dir, name)
}
