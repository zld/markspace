// buildSpec maps CLI options onto the deterministic fixture specification.
// Two video representations (low/high) and one audio track are always present.
func (r *Runner) buildSpec() container.FixtureSpec {
	baseColor := model.ColorMeta{
		Present: true, ColorType: "nclc", Primaries: 1, Transfer: 1, Matrix: 1,
	}
	driftColor := model.ColorMeta{
		Present: true, ColorType: "nclc", Primaries: 9, Transfer: 16, Matrix: 9,
	}
	// 12 seconds, keyframe every 2 seconds => 6 target segments.
	return container.FixtureSpec{
		Name: "asset-17", Seed: r.cfg.Seed, Brand: "isom", MovieTS: 24000,
		Corruption:   r.cfg.Corruption,
		DriftSamples: 3,
		Tracks: []container.TrackSpec{
			{ID: 1, Kind: model.KindVideo, Timescale: 24000, SampleCount: 60,
				SampleDur: 4000, KeyEvery: 10, Color: baseColor, BitrateLabel: "low"},
			{ID: 2, Kind: model.KindVideo, Timescale: 24000, SampleCount: 60,
				SampleDur: 4000, KeyEvery: 10, Color: driftColor, BitrateLabel: "high"},
			{ID: 3, Kind: model.KindAudio, Timescale: 48000, SampleCount: 240,
				SampleDur: 1000, Channels: 2, SampleRate: 48000,
				StartDelay: r.audioDelay()},
		},
	}
}

func (r *Runner) audioDelay() uint64 {
	if r.cfg.Corruption == container.CorruptAudioOffset {
		return 2000
	}
	return 0
}

// countRecoveries counts only genuine structural repairs: rebuilt keyframe
// indexes and trimmed truncated tails. Native stss indexes are not recoveries.
func (r *Runner) countRecoveries(pf *container.ParsedFile) int {
	n := 0
	for _, note := range pf.Recovery {
		if note.Kind == "rebuilt-keyframe-index" || note.Kind == "truncated-box" {
			n++
		}
	}
	return n
}

// roundTrip re-parses the generated bytes and compares the canonical box
// digest against the first parse, yielding the roundtrip success rate.
func (r *Runner) roundTrip(fix *container.Fixture, pf *container.ParsedFile) float64 {
	second, err := container.ParseContainer(fix.Data,
		container.ParseOptions{Data: fix.Data,
			AllowTruncatedRecovery: r.cfg.Corruption == container.CorruptTruncatedBox})
	if err != nil {
		return 0
	}
	if container.BoxDigest(pf.Root) == container.BoxDigest(second.Root) {
		return 1.0
	}
	return 0
}

func (r *Runner) keyframeHitRate(indexes []*container.TrackIndex) float64 {
	var videos, withKeys int
	for _, idx := range indexes {
		if idx.Kind != model.KindVideo {
			continue
		}
		videos++
		if len(idx.Keyframes) > 0 {
			withKeys++
		}
	}
	if videos == 0 {
		return 0
	}
	return float64(withKeys) / float64(videos)
}

func (r *Runner) normalizeMeta(pf *container.ParsedFile) ([]model.Decision, []model.Warning) {
	var decisions []model.Decision
	var warnings []model.Warning
	var refColor model.ColorMeta
	priority := 0
	for _, tr := range pf.Tracks {
		switch tr.Kind {
		case model.KindAudio:
			layout, d := timeline.NormalizeLayout(tr.ID, tr.Audio)
			tr.Audio = layout
			decisions = append(decisions, d)
			_, rateD, w := timeline.NormalizeSampleRate(tr.ID, tr.Audio.SampleRate)
			decisions = append(decisions, rateD)
			if w.Code != "" {
				warnings = append(warnings, w)
			}
		case model.KindVideo:
			if !refColor.Present {
				refColor = tr.Color
			}
			cd, cw := timeline.ColorDecision(tr.ID, priority, tr.Color, refColor)
			decisions = append(decisions, cd)
			warnings = append(warnings, cw...)
			priority++
		}
	}
	return decisions, warnings
}

func (r *Runner) videoTrackClocks(pf *container.ParsedFile) []timeline.TrackClock {
	var out []timeline.TrackClock
	for _, tr := range pf.Tracks {
		if tr.Kind != model.KindVideo {
			continue
		}
		c, _ := timeline.NewClock(tr.Timescale)
		var keys []uint64
		for _, s := range tr.Samples {
			if s.IsKeyframe {
				keys = append(keys, s.DTS)
			}
		}
		out = append(out, timeline.TrackClock{Track: tr, Clock: c, KeyDTS: keys})
	}
	return out
}

func (r *Runner) requiredSegments(pf *container.ParsedFile) int {
	// 12-second asset divided into SegmentMS windows.
	return int(12000 / r.cfg.SegmentMS)
}

func (r *Runner) representations(tcs []timeline.TrackClock) []segmenter.Representation {
	labels := []string{"video-low", "video-high"}
	out := make([]segmenter.Representation, 0, len(tcs))
	for i, tc := range tcs {
		rate := r.cfg.Bitrates[0]
		if i < len(r.cfg.Bitrates) {
			rate = r.cfg.Bitrates[i]
		}
		out = append(out, segmenter.Representation{
			Label:   labels[i],
			Bitrate: rate,
			TrackID: tc.Track.ID,
			Clock:   tc.Clock,
		})
	}
	return out
}
