// Package build orchestrates the end-to-end local HLS pipeline: it generates
// deterministic fixture streams for every tier, slices them into keyframe
// aligned segments, writes master and media playlists atomically, injects
// requested faults, and hands the artefacts to the verifier.
package build

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"streamcheck/internal/fixture"
	"streamcheck/internal/m3u8"
	"streamcheck/internal/pipeline"
	"streamcheck/internal/report"
	"streamcheck/internal/slicer"
	"streamcheck/internal/ts"
	"streamcheck/internal/verify"
)

// TierFault names the faults targeted at a single tier, addressed by tier
// name so the CLI stays independent of internal ordering.
type TierFault struct {
	// HasDrop enables removal of the segment file at DropSegment.
	HasDrop     bool
	DropSegment int
	// HasSwap enables swapping the playlist entries at SwapA and SwapB.
	HasSwap      bool
	SwapA, SwapB int
}

// Config drives one demo/build run.
type Config struct {
	OutDir      string
	Duration    time.Duration
	Segment     time.Duration
	Tiers       []fixture.Tier
	Faults      map[string]TierFault
	Concurrency int
}

// Result is the outcome of a full run across all tiers.
type Result struct {
	Report       report.Report
	TierSegments map[string]int
}

// Run builds every tier concurrently and returns the verification report.
func Run(ctx context.Context, cfg Config) (Result, error) {
	if cfg.Concurrency < 1 {
		cfg.Concurrency = 1
	}
	if err := validateAndPrepare(cfg); err != nil {
		return Result{}, err
	}
	numSegs := int(cfg.Duration / cfg.Segment)
	jobs := make([]pipeline.TierJob, 0, len(cfg.Tiers))
	for _, tier := range cfg.Tiers {
		jobs = append(jobs, pipeline.TierJob{Name: tier.Name})
	}
	results := make([]verify.TierResult, len(cfg.Tiers))
	specs := make([]verify.TierSpec, len(cfg.Tiers))
	worker := func(_ context.Context, job pipeline.TierJob) error {
		idx := tierIndex(cfg.Tiers, job.Name)
		tier := cfg.Tiers[idx]
		res, spec, err := buildTier(cfg, tier, numSegs)
		if err != nil {
			return err
		}
		results[idx] = res
		specs[idx] = spec
		return nil
	}
	if err := pipeline.Run(ctx, jobs, cfg.Concurrency, worker); err != nil {
		return Result{}, err
	}
	// All media playlists are atomically replaced before any segment
	// cleanup, and the master playlist is published last.
	if err := WriteMasterPlaylist(cfg.OutDir, cfg.Tiers); err != nil {
		return Result{}, err
	}
	if err := cleanupUnreferenced(cfg.OutDir, cfg.Tiers, numSegs); err != nil {
		return Result{}, err
	}
	// Cross-tier alignment uses the same shared manifest model.
	checker := verify.NewChecker(cfg.OutDir, 50*time.Millisecond, 0.20)
	cross := checker.CheckCrossTier(results)
	for i := range results {
		results[i].Failures = append(results[i].Failures, cross...)
	}
	return Result{
		Report:       report.FromResults(results),
		TierSegments: countSegments(results),
	}, nil
}

// buildTier generates, slices, manifests and verifies one rendition.
func buildTier(cfg Config, tier fixture.Tier, numSegs int) (verify.TierResult, verify.TierSpec, error) {
	dir := filepath.Join(cfg.OutDir, tier.Name)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return verify.TierResult{}, verify.TierSpec{}, err
	}
	stream := fixture.BuildTier(tier, numSegs, cfg.Segment, fixture.Options{})
	if err := sliceStream(stream, dir); err != nil {
		return verify.TierResult{}, verify.TierSpec{}, err
	}
	sidecar, err := hashSegments(dir, numSegs)
	if err != nil {
		return verify.TierResult{}, verify.TierSpec{}, err
	}
	if err := writeMediaPlaylist(cfg, dir, tier, numSegs, sidecar); err != nil {
		return verify.TierResult{}, verify.TierSpec{}, err
	}
	if err := applyFaults(cfg, dir, tier, numSegs); err != nil {
		return verify.TierResult{}, verify.TierSpec{}, err
	}
	spec := verify.TierSpec{
		Name:       tier.Name,
		BitrateBPS: tier.BandwidthBPS,
		SegmentMS:  cfg.Segment.Milliseconds(),
		Sidecar:    sidecar,
	}
	res := verify.NewChecker(cfg.OutDir, 50*time.Millisecond, 0.20).CheckTier(spec)
	return res, spec, nil
}

// sliceStream runs the real TS scanner + slicer engine over generated bytes.
func sliceStream(stream fixture.BuiltStream, dir string) error {
	eng := slicer.NewEngine(slicer.EngineConfig{
		Window:        slicer.WindowConfig{TargetSegment: 3 * time.Second},
		SegmentPrefix: "seg-",
	})
	src := slicer.NewScannerSource(ts.NewScanner(bytes.NewReader(stream.Data)))
	_, err := slicer.Run(eng, src, dir)
	return err
}

// hashSegments computes the expected SHA-256 of every produced segment.
func hashSegments(dir string, numSegs int) (map[string]string, error) {
	sidecar := make(map[string]string, numSegs)
	for i := 0; i < numSegs; i++ {
		name := segmentName(i)
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(data)
		sidecar[name] = hex.EncodeToString(sum[:])
	}
	return sidecar, nil
}

// writeMediaPlaylist renders the playlist then atomically replaces it.
func writeMediaPlaylist(cfg Config, dir string, tier fixture.Tier,
	numSegs int, sidecar map[string]string) error {
	pl := m3u8.MediaPlaylist{
		Version:        3,
		TargetDuration: cfg.Segment,
		MediaSequence:  0,
		PlaylistType:   "VOD",
		Endlist:        true,
	}
	for i := 0; i < numSegs; i++ {
		pl.Segments = append(pl.Segments, m3u8.Segment{
			URI: segmentName(i), Duration: cfg.Segment,
		})
	}
	return atomicWrite(filepath.Join(dir, "index.m3u8"), func(f *os.File) error {
		return m3u8.WriteMedia(f, pl)
	})
}

// applyFaults mutates the produced artefacts to simulate archive failures.
func applyFaults(cfg Config, dir string, tier fixture.Tier, numSegs int) error {
	fault, ok := cfg.Faults[tier.Name]
	if !ok {
		return nil
	}
	if fault.HasDrop {
		if fault.DropSegment < 0 || fault.DropSegment >= numSegs {
			return fmt.Errorf("drop-segment index %d out of range", fault.DropSegment)
		}
		path := filepath.Join(dir, segmentName(fault.DropSegment))
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	if fault.HasSwap {
		if err := swapPlaylistEntries(filepath.Join(dir, "index.m3u8"),
			fault.SwapA, fault.SwapB, numSegs); err != nil {
			return err
		}
	}
	return nil
}
