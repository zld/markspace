package rtp

import (
	"encoding/binary"
	"fmt"
	"io"
	"os"
	"sort"

	"github.com/pion/rtp"

	"continuity/internal/media"
)

const (
	MediaPayloadType uint8 = 96
	FECPayloadType   uint8 = 127
	fecMagic         byte  = 0xC7
)

// Gap describes one or more sequence numbers that XOR recovery could not mend.
type Gap struct {
	GroupID   byte     `json:"group_id"`
	Sequences []uint16 `json:"sequences"`
	Reason    string   `json:"reason"`
}

// Report is the deterministic result of RTP ordering, dedupe and recovery.
type Report struct {
	Received      int           `json:"received"`
	UniqueMedia   int           `json:"unique_media"`
	Duplicates    int           `json:"duplicates"`
	OutOfOrder    int           `json:"out_of_order"`
	Recovered     int           `json:"recovered"`
	Lost          int           `json:"lost"`
	Unrecoverable int           `json:"unrecoverable"`
	RecoveryRate  float64       `json:"recovery_rate_pct"`
	Gaps          []Gap         `json:"gaps"`
	Ordered       []*rtp.Packet `json:"-"`
}

// ReadRecords reads length-prefixed RTP packets generated by the fixture.
func ReadRecords(path string) ([]*rtp.Packet, error) {
	st, err := os.Stat(path)
	if err != nil {
		return nil, &media.Fault{Phase: media.PhaseRTP, Code: media.CodeInvalidArgument, Source: path, Err: err}
	}
	if st.Size() > media.MaxInputBytes {
		return nil, &media.Fault{Phase: media.PhaseRTP, Code: media.CodeSizeLimit, Source: path, Offset: st.Size()}
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []*rtp.Packet
	var length [4]byte
	for {
		if _, err := io.ReadFull(f, length[:]); err == io.EOF {
			break
		} else if err != nil {
			return nil, rtpFault(path, "record length", err)
		}
		n := binary.BigEndian.Uint32(length[:])
		if n == 0 || n > 64*1024 {
			return nil, &media.Fault{Phase: media.PhaseRTP, Code: media.CodeInvalidArgument, Source: path,
				Offset: st.Size(), Detail: fmt.Sprintf("bad RTP record length %d", n)}
		}
		raw := make([]byte, n)
		if _, err := io.ReadFull(f, raw); err != nil {
			return nil, rtpFault(path, "record payload", err)
		}
		var p rtp.Packet
		if err := p.Unmarshal(raw); err != nil {
			return nil, &media.Fault{Phase: media.PhaseRTP, Code: media.CodeInvalidArgument, Source: path, Err: err}
		}
		out = append(out, &p)
	}
	return out, nil
}

// WriteRecords writes length-prefixed RTP packets in arrival order.
func WriteRecords(path string, packets []*rtp.Packet) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	var lenBuf [4]byte
	for _, p := range packets {
		raw, err := p.Marshal()
		if err != nil {
			return err
		}
		binary.BigEndian.PutUint32(lenBuf[:], uint32(len(raw)))
		if _, err := f.Write(lenBuf[:]); err != nil {
			return err
		}
		if _, err := f.Write(raw); err != nil {
			return err
		}
	}
	return f.Sync()
}

type sequenceWindow struct {
	max uint64
	set bool
}

func (w *sequenceWindow) unwrap(seq uint16) uint64 {
	s := uint64(seq)
	if !w.set {
		w.set = true
		w.max = s
		return s
	}
	candidate := (w.max &^ 0xffff) | s
	if candidate+32768 < w.max {
		candidate += 1 << 16
	} else if candidate > w.max+32768 {
		candidate -= 1 << 16
	}
	if candidate > w.max {
		w.max = candidate
	}
	return candidate
}

// RecoverPackets reorders and deduplicates media packets and applies XOR FEC.
func RecoverPackets(packets []*rtp.Packet) *Report {
	r := &Report{Received: len(packets)}
	mediaBySeq := map[uint16]*rtp.Packet{}
	var maxArrival uint64
	arrivalWindow := sequenceWindow{}
	for _, p := range packets {
		if p.Header.PayloadType == FECPayloadType {
			continue
		}
		ext := arrivalWindow.unwrap(p.Header.SequenceNumber)
		if len(mediaBySeq) > 0 && ext < maxArrival {
			r.OutOfOrder++
		}
		if ext > maxArrival || len(mediaBySeq) == 0 {
			maxArrival = ext
		}
		if _, exists := mediaBySeq[p.Header.SequenceNumber]; exists {
			r.Duplicates++
			continue
		}
		mediaBySeq[p.Header.SequenceNumber] = p
		r.UniqueMedia++
	}

	for _, p := range packets {
		if p.Header.PayloadType != FECPayloadType {
			continue
		}
		groupID, seqs, parity, err := parseFEC(p.Payload)
		if err != nil {
			continue
		}
		var missing []uint16
		for _, seq := range seqs {
			if _, ok := mediaBySeq[seq]; !ok {
				missing = append(missing, seq)
			}
		}
		r.Lost += len(missing)
		switch len(missing) {
		case 0:
			continue
		case 1:
			recovered := xorRecover(seqs, missing[0], mediaBySeq, parity)
			if recovered != nil {
				mediaBySeq[missing[0]] = &rtp.Packet{
					Header:  rtp.Header{Version: 2, PayloadType: MediaPayloadType, SequenceNumber: missing[0], SSRC: p.Header.SSRC},
					Payload: recovered,
				}
				r.Recovered++
			} else {
				r.Unrecoverable++
				r.Gaps = append(r.Gaps, Gap{GroupID: groupID, Sequences: missing, Reason: "xor length mismatch"})
			}
		default:
			r.Unrecoverable += len(missing)
			r.Gaps = append(r.Gaps, Gap{GroupID: groupID, Sequences: missing, Reason: "more than one missing packet in XOR group"})
		}
	}

	type seqKey struct {
		seq uint16
		ext uint64
	}
	keys := make([]seqKey, 0, len(mediaBySeq))
	window := sequenceWindow{}
	for seq := range mediaBySeq {
		keys = append(keys, seqKey{seq: seq, ext: window.unwrap(seq)})
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i].ext < keys[j].ext })
	for _, k := range keys {
		r.Ordered = append(r.Ordered, mediaBySeq[k.seq])
	}
	if total := r.Recovered + r.Unrecoverable; total > 0 {
		r.RecoveryRate = float64(r.Recovered) * 100 / float64(total)
	} else {
		r.RecoveryRate = 100
	}
	return r
}

func xorRecover(group []uint16, missing uint16, packets map[uint16]*rtp.Packet, parity []byte) []byte {
	out := append([]byte(nil), parity...)
	for _, seq := range group {
		if seq == missing {
			continue
		}
		p, ok := packets[seq]
		if !ok || len(p.Payload) > len(out) {
			return nil
		}
		for i, b := range p.Payload {
			out[i] ^= b
		}
	}
	return out
}

func rtpFault(path, stage string, err error) error {
	return &media.Fault{Phase: media.PhaseRTP, Code: media.CodeInvalidArgument, Source: path, Detail: stage, Err: err}
}
