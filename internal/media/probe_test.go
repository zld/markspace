package media

import (
	"testing"

	"archivecheck/internal/diagnostic"
)

func TestProbeGeneratedMP4(t *testing.T) {
	data := GenerateMinimalMP4(MP4Spec{
		TrackID: 7, Timescale: 48000, DurationTicks: 96000,
		Channels: 2, SampleRate: 48000,
	})
	meta, err := ProbeMP4(31, data)
	if err != nil {
		t.Fatalf("ProbeMP4 generated bytes (%d): %v", len(data), err)
	}
	if len(meta.Tracks) != 1 {
		t.Fatalf("tracks = %d, want 1", len(meta.Tracks))
	}
	track := meta.Tracks[0]
	if track.ID != 7 || track.Codec != "mp4a" || track.Channels != 2 {
		t.Fatalf("unexpected track: %+v", track)
	}
	if track.SampleRate != 48000 {
		t.Fatalf("sample rate = %d, want 48000", track.SampleRate)
	}
	if track.DurationNS != 2_000_000_000 {
		t.Fatalf("duration = %d, want 2s", track.DurationNS)
	}
}

func TestProbeTruncatedMP4HasOffset(t *testing.T) {
	full := GenerateMinimalMP4(MP4Spec{})
	truncated := full[:len(full)-72]
	_, err := ProbeMP4(32, truncated)
	if !diagnostic.HasCode(err, diagnostic.CodeTruncated) {
		t.Fatalf("err = %v, want TRUNCATED_INPUT", err)
	}
	de, _ := diagnostic.From(err)
	if de.Sample != 32 || de.Offset != int64(len(truncated)) {
		t.Fatalf("location = sample%d offset%d", de.Sample, de.Offset)
	}
}

func TestAcceptGeneratedDescription(t *testing.T) {
	desc, err := AcceptGeneratedDescription(33, TrackDescription{
		Index: 0, ID: 1, Kind: "audio", Timescale: 48000,
		Channels: 6, ChannelLayout: Layout51, SampleRate: 48000,
	})
	if err != nil {
		t.Fatal(err)
	}
	if desc.Channels != 6 || desc.ChannelLayout != Layout51 {
		t.Fatalf("description changed unexpectedly: %+v", desc)
	}
}
