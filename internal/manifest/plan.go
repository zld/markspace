package manifest

import (
	"sort"

	"archivecheck/internal/model"
)

// Format identifies the manifest syntax.
type Format string

const (
	FormatHLS  Format = "hls"
	FormatDASH Format = "dash"
)

// Range is a byte range in a media resource. End is exclusive.
type Range struct {
	Start int64 `json:"start"`
	End   int64 `json:"end"`
}

// Len returns the number of bytes in the range.
func (r Range) Len() int64 { return r.End - r.Start }

// Valid reports whether the range is non-empty and well-formed.
func (r Range) Valid() bool { return r.Start >= 0 && r.End > r.Start }

// Segment is one media resource plus the exact media interval it covers.
//
// Start and Duration are expressed in ticks of the plan timebase. They are
// derived from decimal or integer inputs without ever discarding a remainder:
// per-segment remainders accumulate in Plan.Remainder so the last segment's
// end lands exactly on the declared duration.
type Segment struct {
	// Index is the 0-based position in the plan.
	Index int `json:"index"`
	// ID is the stable segment identifier used in reports: the media sequence
	// number for HLS, the "$Number$" expansion for DASH.
	ID string `json:"id"`
	// URI is the local resource name relative to the plan root. Empty only
	// for a DASH gap (a segment with no URL).
	URI string `json:"uri"`
	// Range is the optional HLS byte range.
	Range *Range `json:"range,omitempty"`
	// Start and Duration are ticks in Plan.Timebase.
	Start    int64 `json:"start"`
	Duration int64 `json:"duration"`
	// Remainder is the fractional tick carried from the previous segment and
	// generated by this segment's duration. It is preserved for audit.
	Remainder model.Rational `json:"remainder"`
	// EndRemainder is the fractional tick after this segment ends.
	EndRemainder model.Rational `json:"end_remainder"`
	// Discontinuity marks an HLS EXT-X-DISCONTINUITY before this segment or a
	// DASH period boundary.
	Discontinuity bool `json:"discontinuity,omitempty"`
	// Period is the DASH period ID, empty for HLS.
	Period string `json:"period,omitempty"`
	// Representation is the DASH representation ID or the HLS variant ID.
	Representation string `json:"representation,omitempty"`
	// ByteOffset is the absolute offset of Range.Start inside the resource.
	ByteOffset int64 `json:"byte_offset"`
}

// End returns the exclusive end tick of the segment.
func (s Segment) End() int64 { return s.Start + s.Duration }

// Representation is one DASH representation or HLS variant.
type Representation struct {
	ID string `json:"id"`
	// Bandwidth is bits per second; zero when unknown.
	Bandwidth int64 `json:"bandwidth"`
	// Timescale is the representation's own media timescale from the manifest.
	Timescale int64 `json:"timescale"`
	// Base is the tick offset of this representation on the shared timeline.
	Base int64 `json:"base"`
	// Segments are this representation's segments in presentation order.
	Segments []Segment `json:"segments"`
}

// Plan is the unified segment plan produced by every manifest parser.
type Plan struct {
	Format Format `json:"format"`
	// Timebase is the shared integer timebase for every Start and Duration.
	Timebase int64 `json:"timebase"`
	// Source is the manifest file name.
	Source string `json:"source"`
	// Representations are ordered by descending bandwidth, then ID.
	Representations []Representation `json:"representations"`
	// Duration is the total presentation duration in ticks, or -1 when the
	// manifest does not declare one.
	Duration int64 `json:"duration"`
	// Remainder is the exact fractional tick left over from the declared
	// duration conversion.
	Remainder model.Rational `json:"remainder"`
	// TargetDuration is the HLS EXT-X-TARGETDURATION in ticks, or 0.
	TargetDuration int64 `json:"target_duration"`
	// MediaSequence is the first HLS media sequence number, or 0.
	MediaSequence int64 `json:"media_sequence"`
	// Faults collects non-fatal warnings found while parsing.
	Faults *model.FaultList `json:"-"`
}

// NewPlan returns an empty plan with the given format and source.
func NewPlan(format Format, source string) *Plan {
	return &Plan{Format: format, Source: source, Duration: -1, Faults: &model.FaultList{}}
}

// Segments returns every segment across all representations, ordered by start
// time then representation ID.
func (p *Plan) Segments() []Segment {
	var out []Segment
	for _, r := range p.Representations {
		out = append(out, r.Segments...)
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Start != out[j].Start {
			return out[i].Start < out[j].Start
		}
		return out[i].Representation < out[j].Representation
	})
	return out
}

// SegmentCount returns the total number of segments across representations.
func (p *Plan) SegmentCount() int {
	n := 0
	for _, r := range p.Representations {
		n += len(r.Segments)
	}
	return n
}

// Find returns the segment identified by representation and ID.
func (p *Plan) Find(representation, id string) (Segment, bool) {
	for _, r := range p.Representations {
		if r.ID != representation {
			continue
		}
		for _, s := range r.Segments {
			if s.ID == id {
				return s, true
			}
		}
	}
	return Segment{}, false
}

// Timescales returns the distinct declared representation timescales.
func (p *Plan) Timescales() []int64 {
	seen := map[int64]bool{}
	var out []int64
	for _, r := range p.Representations {
		if r.Timescale > 0 && !seen[r.Timescale] {
			seen[r.Timescale] = true
			out = append(out, r.Timescale)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}
