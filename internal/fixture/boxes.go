package fixture

import (
	"encoding/binary"
)

// Box type constants mirror ISO/IEC 14496-12 four-character codes. They are
// local constants so the fixture package has no init-time dependency on the
// parser's string tables.
const (
	boxFtyp = "ftyp"
	boxStyp = "styp"
	boxMoov = "moov"
	boxMvhd = "mvhd"
	boxTrak = "trak"
	boxTkhd = "tkhd"
	boxMdia = "mdia"
	boxMdhd = "mdhd"
	boxHdlr = "hdlr"
	boxMinf = "minf"
	boxMvex = "mvex"
	boxTrex = "trex"
	boxMoof = "moof"
	boxMfhd = "mfhd"
	boxTraf = "traf"
	boxTfhd = "tfhd"
	boxTfdt = "tfdt"
	boxMdat = "mdat"
)

func boxType(name string) []byte {
	if len(name) != 4 {
		panic("box type must be 4 bytes: " + name)
	}
	return []byte(name)
}

// box wraps an already-built payload with an 8-byte small-size header.
func box(name string, payload []byte) []byte {
	out := make([]byte, 8+len(payload))
	binary.BigEndian.PutUint32(out, uint32(8+len(payload)))
	copy(out[4:8], boxType(name))
	copy(out[8:], payload)
	return out
}

// fullBoxPayload prepends the one-byte version and three-byte flags header
// used by FullBox-derived structures.
func fullBoxPayload(version uint8, flags uint32, body []byte) []byte {
	out := make([]byte, 4+len(body))
	out[0] = version
	out[1] = byte(flags >> 16)
	out[2] = byte(flags >> 8)
	out[3] = byte(flags)
	copy(out[4:], body)
	return out
}

func u32(v uint32) []byte {
	b := make([]byte, 4)
	binary.BigEndian.PutUint32(b, v)
	return b
}

func u64(v uint64) []byte {
	b := make([]byte, 8)
	binary.BigEndian.PutUint64(b, v)
	return b
}

// brandBox builds an ftyp/styp payload (major brand, minor version, then the
// compatible brands repeated as four-byte entries).
func brandBox(name, major string, minor uint32, compatible []string) []byte {
	payload := make([]byte, 8+4*len(compatible))
	copy(payload[0:4], major)
	binary.BigEndian.PutUint32(payload[4:8], minor)
	for i, b := range compatible {
		copy(payload[8+4*i:12+4*i], b)
	}
	return box(name, payload)
}

// mvhd builds a minimal version-0 Movie Header Box. Timestamps are fixed
// constants so generated bytes are fully reproducible.
func mvhd(timescale uint32, duration uint32) []byte {
	body := make([]byte, 100)
	binary.BigEndian.PutUint32(body[0:4], 0)   // creation_time
	binary.BigEndian.PutUint32(body[4:8], 0)   // modification_time
	binary.BigEndian.PutUint32(body[8:12], timescale)
	binary.BigEndian.PutUint32(body[12:16], duration)
	binary.BigEndian.PutUint32(body[16:20], 0x00010000) // rate 1.0
	body[20] = 0x01                                     // volume 1.0
	// next_track_id at offset 96
	binary.BigEndian.PutUint32(body[96:100], 2)
	return box(boxMvhd, fullBoxPayload(0, 0, body))
}

// tkhd builds a minimal version-0 Track Header Box.
func tkhd(trackID, duration uint32) []byte {
	body := make([]byte, 84)
	binary.BigEndian.PutUint32(body[0:4], 0) // creation_time
	binary.BigEndian.PutUint32(body[4:8], 0) // modification_time
	binary.BigEndian.PutUint32(body[8:12], trackID)
	binary.BigEndian.PutUint32(body[12:16], 0) // reserved
	binary.BigEndian.PutUint32(body[16:20], duration)
	body[20] = 0x07 // reserved
	body[21] = 0xff
	body[22] = 0xff
	body[23] = 0
	body[24] = 0
	body[25] = 0
	body[26] = 0x02 // volume
	// identity matrix at offset 36
	matrix := []uint32{0x00010000, 0, 0, 0, 0x00010000, 0, 0, 0, 0x40000000}
	for i, m := range matrix {
		binary.BigEndian.PutUint32(body[36+4*i:40+4*i], m)
	}
	binary.BigEndian.PutUint32(body[76:80], 0x00010000) // width=1
	binary.BigEndian.PutUint32(body[80:84], 0x00010000) // height=1
	return box(boxTkhd, fullBoxPayload(0, 0x000007, body))
}

// mdhd builds a version-0 Media Header Box carrying the track timescale.
func mdhd(timescale, duration uint32) []byte {
	body := make([]byte, 20)
	binary.BigEndian.PutUint32(body[0:4], 0) // creation_time
	binary.BigEndian.PutUint32(body[4:8], 0) // modification_time
	binary.BigEndian.PutUint32(body[8:12], timescale)
	binary.BigEndian.PutUint32(body[12:16], duration)
	body[16] = 0x55 // language 'und'
	body[17] = 0xc4
	return box(boxMdhd, fullBoxPayload(0, 0, body))
}

// hdlr builds a minimal Handler Box declaring a video track.
func hdlr() []byte {
	body := make([]byte, 21)
	copy(body[4:8], "vide")
	return box(boxHdlr, fullBoxPayload(0, 0, body))
}

// trex builds a Track Extends Box for the mvex container.
func trex(trackID uint32) []byte {
	body := make([]byte, 20)
	binary.BigEndian.PutUint32(body[0:4], trackID)
	binary.BigEndian.PutUint32(body[4:8], 1) // sample_description_index
	return box(boxTrex, fullBoxPayload(0, 0, body))
}

// mfhd builds a Movie Fragment Header Box with the given sequence number.
func mfhd(sequence uint32) []byte {
	return box(boxMfhd, fullBoxPayload(0, 0, u32(sequence)))
}

// tfhd builds a Track Fragment Header Box.
func tfhd(trackID uint32) []byte {
	return box(boxTfhd, fullBoxPayload(0, 0, u32(trackID)))
}

// tfdt builds a version-1 (64-bit) Track Fragment Base Media Decode Time Box.
func tfdt(baseTime uint64) []byte {
	return box(boxTfdt, fullBoxPayload(1, 0, u64(baseTime)))
}
