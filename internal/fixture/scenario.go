package fixture

import (
	"fmt"
	"math/big"
	"math/rand"

	"github.com/zld/mediarc/internal/model"
)

// SampleSpec is a generator's intended sample before MP4 serialization.
type SampleSpec struct {
	SampleNumber uint32
	SharedNS     model.NS
	SourceNS     model.NS
	Ticks        uint64
	Delta        uint32
	Keyframe     bool
	OrderIndex   int
	Payload      []byte
}

// RepSpec is one generated bitrate representation/track.
type RepSpec struct {
	TrackID   uint32
	Name      string
	Timescale uint32
	Bitrate   int
	DriftPPM  int64
	Samples   []SampleSpec
	Anchors   []model.Anchor
}

// DemoAsset contains generated bytes and the server-side expected payloads.
type DemoAsset struct {
	Seed          int64
	InputName     string
	MP4           []byte
	SttsOffsets   map[uint32]int64
	MdhdOffsets   map[uint32]int64
	Reps          []*RepSpec
	Config        model.Config
	LateEvent     model.RawEvent
	CorruptOffset int64
}

// Payload returns deterministic sample bytes for generated normal samples.
func (a *DemoAsset) Payload(trackID, sampleNumber uint32) []byte {
	for _, rep := range a.Reps {
		if rep.TrackID != trackID {
			continue
		}
		for _, s := range rep.Samples {
			if s.SampleNumber == sampleNumber {
				return s.Payload
			}
		}
	}
	if a.LateEvent.TrackID == trackID && a.LateEvent.SampleNumber == sampleNumber {
		return a.LateEvent.Payload
	}
	return nil
}

func sharedBoundaries() []model.NS {
	return []model.NS{0, 2 * model.Second, 4 * model.Second, 6 * model.Second, 6500 * model.Millisecond}
}

func variableFrameTimes(bounds []model.NS) []model.NS {
	weights := []int64{3, 1, 2, 4, 2, 1}
	times := []model.NS{bounds[0]}
	for bi := 0; bi+1 < len(bounds); bi++ {
		start, end := bounds[bi], bounds[bi+1]
		span := int64(end - start)
		var sumWeights int64
		for _, w := range weights {
			sumWeights += w
		}
		cursor := int64(start)
		allocated := int64(0)
		for j, w := range weights {
			var d int64
			if j == len(weights)-1 {
				d = int64(end) - cursor
			} else {
				d = span * w / sumWeights
				allocated += d
			}
			cursor += d
			if j == len(weights)-1 {
				times = append(times, model.NS(cursor))
			} else {
				times = append(times, model.NS(cursor))
			}
		}
		_ = allocated
	}
	return times
}

func driftTime(shared model.NS, ppm int64) model.NS {
	if ppm == 0 {
		return shared
	}
	num := big.NewInt(int64(shared) * (1_000_000 + ppm))
	den := big.NewInt(1_000_000)
	return model.NS(new(big.Int).Quo(num, den).Int64())
}

func ticksForNS(t model.NS, timescale uint32) uint64 {
	num := new(big.Int).Mul(big.NewInt(int64(t)), big.NewInt(int64(timescale)))
	q := new(big.Int).Quo(num, big.NewInt(int64(model.Second)))
	return q.Uint64()
}

func payloadFor(seed int64, trackID, sample uint32) []byte {
	r := rand.New(rand.NewSource(seed + int64(trackID)*1_000_003 + int64(sample)*37))
	size := 48 + r.Intn(64)
	b := make([]byte, size)
	_, _ = r.Read(b)
	return append([]byte(fmt.Sprintf("MEDIARC|seed=%d|track=%d|sample=%d|", seed, trackID, sample)), b...)
}

func buildRep(seed int64, trackID uint32, name string, timescale uint32, bitrate int, ppm int64, times []model.NS, bounds []model.NS) *RepSpec {
	boundarySet := map[model.NS]bool{}
	for _, b := range bounds {
		boundarySet[b] = true
	}
	rep := &RepSpec{TrackID: trackID, Name: name, Timescale: timescale, Bitrate: bitrate, DriftPPM: ppm}
	ticks := make([]uint64, len(times))
	source := make([]model.NS, len(times))
	for i, t := range times {
		source[i] = driftTime(t, ppm)
		ticks[i] = ticksForNS(source[i], timescale)
	}
	for i, t := range times {
		var delta uint32
		if i+1 < len(ticks) {
			delta = uint32(ticks[i+1] - ticks[i])
		} else if i > 0 {
			delta = uint32(ticks[i] - ticks[i-1])
		}
		s := SampleSpec{
			SampleNumber: uint32(i + 1),
			SharedNS:     t,
			SourceNS:     source[i],
			Ticks:        ticks[i],
			Delta:        delta,
			Keyframe:     boundarySet[t],
			OrderIndex:   i,
			Payload:      payloadFor(seed, trackID, uint32(i+1)),
		}
		rep.Samples = append(rep.Samples, s)
		if s.Keyframe {
			sourceNS, _ := model.SignedToNS(int64(ticks[i]), timescale)
			rep.Anchors = append(rep.Anchors, model.Anchor{TrackID: trackID, SourceNS: sourceNS, SharedNS: t, Stable: true})
		}
	}
	return rep
}

func lateEvent(seed int64, rep *RepSpec) model.RawEvent {
	// Insert immediately after the eleventh continuous sample, so recovery can
	// use the eight-event checkpoint. Duplicating its timestamp makes modular
	// unwrapping unambiguous in the self-test.
	anchor := rep.Samples[10]
	return model.RawEvent{
		TrackID:        rep.TrackID,
		Representation: rep.Name,
		SampleNumber:   900001,
		ArrivalIndex:   1_000_000,
		OrderIndex:     anchor.OrderIndex,
		RawTimestamp:   anchor.Ticks & ((uint64(1) << 32) - 1),
		TimestampBits:  32,
		Timescale:      rep.Timescale,
		RawNS:          anchor.SharedNS,
		DurationNS:     0,
		Keyframe:       false,
		Payload:        payloadFor(seed+999, rep.TrackID, 900001),
	}
}
