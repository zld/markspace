// Package fixture generates self-contained sample subtitle files.
package fixture

import (
	"fmt"
	"os"
	"path/filepath"
)

// mixedSRT holds 6 cues: cue 4 is fully covered by cue 3, cue 5 partly
// overlaps cue 3. keep yields 6 cues, trim yields 5 with 1 dropped.
const mixedSRT = `1
00:00:01,000 --> 00:00:03,000
第一关开场白

2
00:00:03,500 --> 00:00:05,000
守卫：站住！

3
00:00:05,000 --> 00:00:08,000
旁白：城门缓缓打开
风从街道尽头吹来

4
00:00:06,000 --> 00:00:07,000
被完全覆盖的台词

5
00:00:07,500 --> 00:00:09,000
部分重叠的台词

6
00:00:10,000 --> 00:00:12,000
结束语
`

const sampleVTT = `WEBVTT - fixture

NOTE generated by subx fixture

intro
00:00:01.000 --> 00:00:02.500
过场字幕第一行

00:00:03.000 --> 00:00:04.500 line:90%
过场字幕第二行
`

// Generate writes the sample files into dir and returns their paths.
func Generate(dir string) ([]string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("create fixture dir: %v", err)
	}
	files := map[string]string{
		"mixed.srt":  mixedSRT,
		"sample.vtt": sampleVTT,
	}
	var paths []string
	for name, content := range files {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("write fixture %s: %v", name, err)
		}
		paths = append(paths, p)
	}
	return paths, nil
}
