// Package fixture generates all sample inputs used by demos and tests.
// Everything is derived from an explicit seed and deterministic, so the same
// parameters always produce byte-identical WAV and RTP inputs and summaries.
package fixture

import (
	"encoding/binary"
	"math"
	"time"

	"mediasync/internal/clock"
	"mediasync/internal/rtp"
)

// AudioConfig describes the generated capture stream geometry.
type AudioConfig struct {
	SampleRate       int
	Channels         int
	BitsPerSample    int
	PacketSamples    int // PCM frames per RTP packet (480 for 10 ms @48k)
	Duration         time.Duration
	SSRC             uint32
	BaseSeq          uint16
	BaseTS           uint32
	ClockTicksPerPkt clock.Tick
}

// DefaultAudioConfig returns the 30 s / 48 kHz / stereo / 10 ms packet shape
// referenced by the performance target.
func DefaultAudioConfig(d time.Duration) AudioConfig {
	const framesPerPkt = 480
	return AudioConfig{
		SampleRate:       48000,
		Channels:         2,
		BitsPerSample:    16,
		PacketSamples:    framesPerPkt,
		Duration:         d,
		SSRC:             0x5151,
		BaseSeq:          100,
		BaseTS:           9000,
		ClockTicksPerPkt: clock.Tick(int64(framesPerPkt) * clock.TicksPerSecond / 48000),
	}
}

// BlockAlign returns bytes per multi-channel sample frame.
func (c AudioConfig) BlockAlign() int { return c.Channels * c.BitsPerSample / 8 }

// PacketCount is the number of RTP packets covering the duration.
func (c AudioConfig) PacketCount() int {
	total := int(c.Duration.Seconds()*float64(c.SampleRate)) / c.PacketSamples
	return total
}

// Plan is the fault-injection specification for a generated stream.
type Plan struct {
	Seed            int64
	LossBurst       int // size of one mid-stream loss burst (0 disables)
	Reorder         int // number of packets swapped with their successor
	TruncateAudio   int // bytes removed from the WAV tail (0 disables)
	CorruptIndex    int // number of bogus records injected later by the pipeline
	ForceDependency int // when >0, node named below fails this many attempts
	FailNode        string
}

// Stream bundles a generated capture stream and the faults applied to it.
type Stream struct {
	Config     AudioConfig
	Plan       Plan
	WAV        []byte // intact WAV, before truncation
	PCM        []byte // intact PCM payload
	Packets    []*rtp.Packet
	SentSeqs   []uint16 // wire sequence numbers actually emitted (loss/reorder applied)
	LostSeqs   []int64  // extended sequence numbers removed
	FrameCount int
}

// rng is a tiny deterministic xorshift64* PRNG so fixture bytes never depend
// on map iteration or the global rand source.
type rng struct{ s uint64 }

func newRNG(seed int64) *rng {
	s := uint64(seed)
	if s == 0 {
		s = 0x9E3779B97F4A7C15
	}
	return &rng{s: s}
}

func (r *rng) next() uint64 {
	r.s ^= r.s >> 12
	r.s ^= r.s << 25
	r.s ^= r.s >> 27
	return r.s * 0x2545F4914F6CDD1D
}

func (r *rng) intn(n int) int {
	if n <= 0 {
		return 0
	}
	return int(r.next() % uint64(n))
}

// Generate builds an intact WAV file plus the ordered set of RTP packets
// after applying the loss and reorder parts of the plan. Truncation is kept
// separate so callers can also parse the pristine file.
func Generate(cfg AudioConfig, plan Plan) (*Stream, error) {
	if cfg.Channels < 1 || cfg.Channels > 8 || (cfg.BitsPerSample != 16 && cfg.BitsPerSample != 24) {
		return nil, clock.NewError(clock.ErrInvalidArgument, "invalid audio geometry")
	}
	n := cfg.PacketCount()
	if n <= 0 {
		return nil, clock.NewError(clock.ErrInvalidArgument, "duration too short for one packet")
	}
	r := newRNG(plan.Seed)
	pcm := make([]byte, n*cfg.PacketSamples*cfg.BlockAlign())
	fillPCM(r, pcm, cfg)

	// Build packets in source order, one timestamp per 10 ms frame.
	packets := make([]*rtp.Packet, 0, n)
	for i := 0; i < n; i++ {
		seq := uint16(int(cfg.BaseSeq) + i)
		ts := cfg.BaseTS + uint32(int64(i)*int64(cfg.ClockTicksPerPkt))
		start := i * cfg.PacketSamples * cfg.BlockAlign()
		end := start + cfg.PacketSamples*cfg.BlockAlign()
		buf, err := rtp.MarshalPacket(seq, ts, cfg.SSRC, pcm[start:end])
		if err != nil {
			return nil, err
		}
		p, err := rtp.ParsePacket(buf)
		if err != nil {
			return nil, err
		}
		packets = append(packets, p)
	}

	stream := &Stream{Config: cfg, Plan: plan, PCM: pcm, Packets: packets,
		FrameCount: n * cfg.PacketSamples}
	stream.WAV = buildWAV(cfg, pcm)
	applyFaults(stream, r)
	return stream, nil
}

// fillPCM writes deterministic 16/24-bit PCM samples: a low-amplitude sine
// so generated bytes are patterned rather than all-zero silence.
func fillPCM(r *rng, pcm []byte, cfg AudioConfig) {
	ba := cfg.BlockAlign()
	frames := len(pcm) / ba
	for f := 0; f < frames; f++ {
		for ch := 0; ch < cfg.Channels; ch++ {
			v := int32(math.Sin(float64(f+ch)*0.05) * 4000)
			pos := f*ba + ch*cfg.BitsPerSample/8
			switch cfg.BitsPerSample {
			case 16:
				binary.LittleEndian.PutUint16(pcm[pos:], uint16(v))
			case 24:
				u := uint32(v)
				pcm[pos] = byte(u)
				pcm[pos+1] = byte(u >> 8)
				pcm[pos+2] = byte(u >> 16)
			}
		}
	}
	_ = r // reserved for future jitter on sample values
}

// applyFaults removes one loss burst and performs deterministic adjacent
// swaps, recording exactly which extended sequences disappeared.
func applyFaults(s *Stream, r *rng) {
	n := len(s.Packets)
	drop := map[int]bool{}
	if s.Plan.LossBurst > 0 && s.Plan.LossBurst < n-2 {
		start := 2 + r.intn(n-s.Plan.LossBurst-4)
		for i := 0; i < s.Plan.LossBurst; i++ {
			drop[start+i] = true
			s.LostSeqs = append(s.LostSeqs, int64(s.Config.BaseSeq)+int64(start+i))
		}
	}

	kept := make([]*rtp.Packet, 0, n-len(drop))
	for i, p := range s.Packets {
		if !drop[i] {
			kept = append(kept, p)
		}
	}
	swaps := s.Plan.Reorder
	if swaps > len(kept)/2 {
		swaps = len(kept) / 2
	}
	used := map[int]bool{}
	for k := 0; k < swaps; k++ {
		i := 1 + r.intn(len(kept)-2)
		if used[i] || used[i+1] {
			continue
		}
		used[i], used[i+1] = true, true
		kept[i], kept[i+1] = kept[i+1], kept[i]
	}
	s.Packets = kept
	s.SentSeqs = make([]uint16, len(kept))
	for i, p := range kept {
		s.SentSeqs[i] = p.SequenceNumber
	}
}

// TruncatedWAV returns the WAV bytes with tail bytes removed per the plan.
// It never mutates the pristine stream.WAV.
func (s *Stream) TruncatedWAV() []byte {
	if s.Plan.TruncateAudio <= 0 || s.Plan.TruncateAudio >= len(s.WAV) {
		return s.WAV
	}
	out := make([]byte, len(s.WAV)-s.Plan.TruncateAudio)
	copy(out, s.WAV[:len(out)])
	return out
}
