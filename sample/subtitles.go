// Package sample generates the fixtures the acceptance run uses: subtitle
// documents, an MP4 with a valid index, a truncated MP4, an MP4 with an index
// that points past the end, and RTP packet streams with loss and reordering.
//
// All fixtures are produced by code with a fixed seed; no external media is
// read and no network is used.
package sample

import (
	"fmt"
)

// Scene is one subtitle cue in the generated fixture, expressed in frames of
// the fixture's timecode rate.
type Scene struct {
	StartFrames int64
	EndFrames   int64
	Text        string
}

// SubtitleFixture is a generated subtitle document.
type SubtitleFixture struct {
	// Name is the file name inside the sample directory.
	Name string
	// Data is the document bytes.
	Data []byte
	// ValidCues is the number of cues a recovering parser should recover.
	ValidCues int
	// InvalidCues is the number of blocks that must be reported as invalid.
	InvalidCues int
}

// scenes are the nominal cues used by every generated subtitle fixture.
func scenes() []Scene {
	return []Scene{
		{StartFrames: 25, EndFrames: 75, Text: "Opening credits"},
		{StartFrames: 100, EndFrames: 150, Text: "A quiet archive"},
		{StartFrames: 200, EndFrames: 275, Text: "Subtitles recovered"},
		{StartFrames: 300, EndFrames: 350, Text: "End of reel one"},
	}
}

// frameClock renders a frame count at 25 fps as an SRT timestamp.
func frameClock(frames int64) string {
	total := frames * 1000 / 25
	hours := total / 3_600_000
	total %= 3_600_000
	minutes := total / 60_000
	total %= 60_000
	seconds := total / 1000
	millis := total % 1000
	return fmt.Sprintf("%02d:%02d:%02d,%03d", hours, minutes, seconds, millis)
}

// vttClock renders a frame count at 25 fps as a WebVTT timestamp.
func vttClock(frames int64) string {
	return "00:00:" + fmt.Sprintf("%02d.%03d", frames*1000/25/1000, frames*1000/25%1000)
}

// BuildSRT generates an SRT document. When corrupt is true two malformed cues
// are spliced in between the valid ones.
func BuildSRT(corrupt bool) SubtitleFixture {
	data := ""
	valid := 0
	invalid := 0
	for i, scene := range scenes() {
		data += fmt.Sprintf("%d\n%s --> %s\n%s\n\n", i+1, frameClock(scene.StartFrames), frameClock(scene.EndFrames), scene.Text)
		valid++
		if corrupt && i == 1 {
			data += "99\n00:00:07,000 -> 00:00:08,000\nmissing arrow body\n\n"
			invalid++
		}
		if corrupt && i == 2 {
			data += "98\n00:00:09,000 --> 00:00:08,000\nbackwards cue\n\n"
			invalid++
		}
	}
	return SubtitleFixture{Name: "subtitles.srt", Data: []byte(data), ValidCues: valid, InvalidCues: invalid}
}

// BuildVTT generates a WebVTT document with header metadata, a NOTE block and
// the same cues as BuildSRT.
func BuildVTT() SubtitleFixture {
	data := "WEBVTT\nKind: captions\nLanguage: en\n\nNOTE generated by mediarc\n\nSTYLE\n::cue { color: #eee }\n\n"
	valid := 0
	for i, scene := range scenes() {
		data += fmt.Sprintf("cue-%d\n%s --> %s align:start\n%s\n\n", i+1,
			vttClock(scene.StartFrames), vttClock(scene.EndFrames), scene.Text)
		valid++
	}
	return SubtitleFixture{Name: "subtitles.vtt", Data: []byte(data), ValidCues: valid}
}
