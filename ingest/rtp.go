package ingest

import (
	"fmt"

	"github.com/pion/rtp"

	"mediapack/model"
)

// Gap describes a contiguous range of RTP sequence numbers that could not be
// recovered inside the reorder window.
type Gap struct {
	Track model.TrackID `json:"track"`
	Start uint16        `json:"start_sequence"`
	End   uint16        `json:"end_sequence"`
	Count int           `json:"count"`
}

// RTPStats contains auditable sequence recovery counters.
type RTPStats struct {
	Track               model.TrackID `json:"track"`
	PacketsIn           int           `json:"packets_in"`
	UniquePackets       int           `json:"unique_packets"`
	DuplicatePackets    int           `json:"duplicate_packets"`
	OutOfOrderPackets   int           `json:"out_of_order_packets"`
	ReorderedRecovered  int           `json:"reordered_recovered"`
	DeliveredPackets    int           `json:"delivered_packets"`
	Gaps                []Gap         `json:"gaps"`
	UnrecoveredPackets  int           `json:"unrecovered_packets"`
	LateOutsideWindow   int           `json:"late_outside_window_packets"`
	ReorderRecoveryRate float64       `json:"reorder_recovery_rate"`
	LossRecoveryRate    float64       `json:"loss_recovery_rate"`
	RecoveryRate        float64       `json:"recovery_rate"`
}

// ParseRTP parses one complete RTP datagram using pion/rtp.
func ParseRTP(data []byte) (*rtp.Packet, error) {
	var p rtp.Packet
	if err := p.Unmarshal(data); err != nil {
		return nil, model.NewError("", "rtp", 0, model.CategoryInvalidArgument, "invalid RTP packet", err)
	}
	return &p, nil
}

// sequenceForward returns the circular forward distance from a to b.
func sequenceForward(a, b uint16) int {
	return int((uint32(b) - uint32(a)) & 0xffff)
}

// RTPReorder restores bounded RTP reordering and records unrecoverable gaps.
// It is not safe for concurrent use; one instance owns one RTP/SSRC stream.
type RTPReorder struct {
	track    model.TrackID
	window   int
	initial  uint16
	started  bool
	expected uint16
	buffer   map[uint16]*rtp.Packet
	recent   map[uint16]struct{}

	stats RTPStats
}

// NewRTPReorder creates a buffer accepting sequences at most window positions
// ahead of the next contiguous sequence.
func NewRTPReorder(track model.TrackID, window int, initialSequence uint16) *RTPReorder {
	if window < 1 {
		window = 1
	}
	return &RTPReorder{
		track:    track,
		window:   window,
		initial:  initialSequence,
		expected: initialSequence,
		buffer:   make(map[uint16]*rtp.Packet),
		recent:   make(map[uint16]struct{}),
		stats:    RTPStats{Track: track},
	}
}

// Stats returns a copy of the current recovery statistics.
func (r *RTPReorder) Stats() RTPStats {
	s := r.stats
	s.Gaps = append([]Gap(nil), r.stats.Gaps...)
	if r.stats.OutOfOrderPackets > 0 {
		s.ReorderRecoveryRate = float64(r.stats.ReorderedRecovered) / float64(r.stats.OutOfOrderPackets)
	} else {
		s.ReorderRecoveryRate = 1
	}
	// No retransmission/FEC is generated by this local kernel. Every detected
	// permanent loss is therefore unrecovered; the ratio makes that explicit.
	totalLoss := r.stats.UnrecoveredPackets
	if totalLoss == 0 {
		s.LossRecoveryRate = 1
	} else {
		s.LossRecoveryRate = 0
	}
	s.RecoveryRate = s.ReorderRecoveryRate
	return s
}

// Push accepts one packet and returns any newly contiguous packets. A packet
// beyond the reorder window finalizes the gap before it and allows processing
// to continue.
func (r *RTPReorder) Push(p *rtp.Packet) ([]*rtp.Packet, error) {
	if p == nil {
		return nil, model.NewError(r.track, "rtp", -1, model.CategoryInvalidArgument, "nil RTP packet", nil)
	}
	r.stats.PacketsIn++
	seq := p.SequenceNumber

	if _, dupBuffered := r.buffer[seq]; dupBuffered {
		r.stats.DuplicatePackets++
		return nil, nil
	}
	if _, dupRecent := r.recent[seq]; dupRecent {
		r.stats.DuplicatePackets++
		return nil, nil
	}
	if r.started {
		behind := sequenceForward(seq, r.expected)
		if behind > 0 && behind < 0x8000 {
			// Exact delivered repeats were handled by r.recent above. An
			// unrecognized behind-expected packet is late for a gap already
			// finalized; it must not be delivered or counted as a repeat.
			r.stats.LateOutsideWindow++
			return nil, nil
		}
	}

	r.started = true
	r.stats.UniquePackets++
	distance := sequenceForward(r.expected, seq)

	// A far-ahead packet means the missing region has exceeded the window.
	if distance > r.window {
		return r.skipGapUntil(seq, p)
	}

	if seq != r.expected {
		r.stats.OutOfOrderPackets++
		r.buffer[seq] = p
		return nil, nil
	}

	var out []*rtp.Packet
	out = append(out, r.deliver(p))
	r.expected = seq + 1
	out = append(out, r.drain()...)
	return out, nil
}

func (r *RTPReorder) skipGapUntil(target uint16, targetPacket *rtp.Packet) ([]*rtp.Packet, error) {
	var out []*rtp.Packet
	missing := 0
	start := r.expected
	for seq := r.expected; seq != target; seq++ {
		if p, ok := r.buffer[seq]; ok {
			r.stats.ReorderedRecovered++
			out = append(out, r.deliver(p))
			delete(r.buffer, seq)
		} else {
			missing++
		}
		r.expected = seq + 1
	}
	if missing > 0 {
		gap := Gap{Track: r.track, Start: start, End: target - 1, Count: missing}
		r.stats.Gaps = append(r.stats.Gaps, gap)
		r.stats.UnrecoveredPackets += missing
	}
	out = append(out, r.deliver(targetPacket))
	r.expected = target + 1
	out = append(out, r.drain()...)
	return out, nil
}

func (r *RTPReorder) deliver(p *rtp.Packet) *rtp.Packet {
	r.stats.DeliveredPackets++
	seq := p.SequenceNumber
	r.recent[seq] = struct{}{}
	if len(r.recent) > 4*r.window+16 {
		// Prune the oldest replay entries conservatively by circular distance.
		for old := range r.recent {
			if sequenceForward(old, r.expected) > 2*r.window+8 {
				delete(r.recent, old)
			}
		}
	}
	return p
}

func (r *RTPReorder) drain() []*rtp.Packet {
	var out []*rtp.Packet
	for {
		p, ok := r.buffer[r.expected]
		if !ok {
			return out
		}
		delete(r.buffer, r.expected)
		// Every drained buffer entry had arrived out-of-order.
		r.stats.ReorderedRecovered++
		out = append(out, r.deliver(p))
		r.expected++
	}
}

// Finish abandons a trailing gap and delivers any remaining buffered contiguous
// suffix. It must be called once after the final pushed packet.
func (r *RTPReorder) Finish() []*rtp.Packet {
	var out []*rtp.Packet
	// If expected is absent but later buffered packets exist, count the
	// contiguous missing prefix then deliver the suffix in order.
	for len(r.buffer) > 0 {
		if p, ok := r.buffer[r.expected]; ok {
			delete(r.buffer, r.expected)
			r.stats.ReorderedRecovered++
			out = append(out, r.deliver(p))
			r.expected++
			continue
		}

		// Find the smallest circular-ahead buffered sequence.
		var next uint16
		best := 1 << 16
		for seq := range r.buffer {
			d := sequenceForward(r.expected, seq)
			if d < best {
				best = d
				next = seq
			}
		}
		missing := best
		if missing > 0 {
			r.stats.Gaps = append(r.stats.Gaps, Gap{
				Track: r.track, Start: r.expected, End: next - 1, Count: missing,
			})
			r.stats.UnrecoveredPackets += missing
			r.expected = next
		}
	}
	return out
}

// ExplainLosses is a small helper used by tests and CLI diagnostics.
func ExplainLosses(losses []int) string {
	return fmt.Sprintf("configured_losses=%v", losses)
}
