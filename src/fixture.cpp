FixtureArtifacts generateFixtures(const FixtureOptions& opts) {
    if (opts.grid < kMinCubeGrid || opts.grid > kMaxCubeGrid) {
        throw UsageError("fixture grid must be in [" +
                         std::to_string(kMinCubeGrid) + ", " +
                         std::to_string(kMaxCubeGrid) + "]");
    }
    std::error_code ec;
    std::filesystem::create_directories(opts.dir, ec);
    if (ec) {
        throw IoError("cannot create fixture directory '" + opts.dir +
                      "': " + ec.message());
    }

    FixtureArtifacts artifacts;
    artifacts.inputPath = opts.dir + "/input.ppm";
    artifacts.lutPath = opts.dir + "/look.cube";
    artifacts.patchesPath = opts.dir + "/patches.ppm";

    writeTextFile(artifacts.lutPath, writeCubeLook(opts.grid));
    PpmImage gradient = buildGradient(opts.width, opts.height);
    writePpmFileAtomic(artifacts.inputPath, gradient);
    writePpmFileAtomic(artifacts.patchesPath, buildPatches());

    // Round-trip every artifact through the real parsers so a broken
    // fixture fails generation rather than a later render step.
    CubeLut checked = parseCubeFile(artifacts.lutPath);
    if (checked.gridSize() != opts.grid) {
        throw FormatError("fixture LUT grid size mismatch after write");
    }
    PpmImage checkedImage = readPpmFile(artifacts.inputPath);
    if (checkedImage.width() != opts.width ||
        checkedImage.height() != opts.height) {
        throw FormatError("fixture image dimensions mismatch after write");
    }
    return artifacts;
}

