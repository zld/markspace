// A smooth, monotonic S-curve used as the per-channel transfer. It stays
// inside [0, 1] for in-range input, which keeps the fixture realistic.
double smooth_curve(double x) {
  const double t = x < 0.0 ? 0.0 : (x > 1.0 ? 1.0 : x);
  return t * t * (3.0 - 2.0 * t);
}

// Small deterministic mix, 4% cross-channel, to catch axis transposition.
constexpr double kMix = 0.04;

double fmt_trimmed(double value) {
  // Fixed precision keeps fixture bytes stable across runs and stdlibs.
  char buffer[64];
  std::snprintf(buffer, sizeof(buffer), "%.9f", value);
  return std::strtod(buffer, nullptr);
}

std::string sample_line(double r, double g, double b) {
  std::ostringstream out;
  out << "  " << fmt_trimmed(r) << ' ' << fmt_trimmed(g) << ' ' << fmt_trimmed(b)
      << '\n';
  return out.str();
}

