void write_fixture_lut(const std::string& path, int size) {
  if (size < kMinGridSize || size > kMaxGridSize) {
    fail(ExitCode::Usage, "fixture LUT size must be in [" +
                              std::to_string(kMinGridSize) + ", " +
                              std::to_string(kMaxGridSize) + "]");
  }
  std::ofstream out(path, std::ios::binary | std::ios::trunc);
  if (!out) {
    fail(ExitCode::Output, path + ": cannot create fixture LUT");
  }
  out << "TITLE \"lutcheck deterministic grade\"\n";
  out << "# Generated by lutcheck; do not edit by hand.\n";
  out << "LUT_3D_SIZE " << size << '\n';
  out << "DOMAIN_MIN 0.000000000 0.000000000 0.000000000\n";
  out << "DOMAIN_MAX 1.000000000 1.000000000 1.000000000\n";
  const double denom = static_cast<double>(size - 1);
  // Blue-major, red-fastest: the order mandated by .cube.
  for (int b = 0; b < size; ++b) {
    for (int g = 0; g < size; ++g) {
      for (int r = 0; r < size; ++r) {
        const double rr = r / denom;
        const double gg = g / denom;
        const double bb = b / denom;
        const double sr = smooth_curve(rr);
        const double sg = smooth_curve(gg);
        const double sb = smooth_curve(bb);
        out << sample_line(sr * (1.0 - kMix) + sg * kMix,
                           sg * (1.0 - kMix) + sb * kMix,
                           sb * (1.0 - kMix) + sr * kMix);
      }
    }
  }
  out.flush();
  if (!out) {
    fail(ExitCode::Output, path + ": write failure");
  }
}

Image make_fixture_image(std::size_t width, std::size_t height) {
  if (width == 0 || height == 0) {
    fail(ExitCode::Usage, "fixture image dimensions must be positive");
  }
  if (width * height > kMaxPixels) {
    fail(ExitCode::Usage, "fixture image exceeds the pixel limit");
  }
  Image image;
  image.width = static_cast<std::uint32_t>(width);
  image.height = static_cast<std::uint32_t>(height);
  image.pixels.resize(width * height);
  const double w = static_cast<double>(width > 1 ? width - 1 : 1);
  const double h = static_cast<double>(height > 1 ? height - 1 : 1);
  for (std::size_t y = 0; y < height; ++y) {
    for (std::size_t x = 0; x < width; ++x) {
      const double u = static_cast<double>(x) / w;
      const double v = static_cast<double>(y) / h;
      const std::size_t index = y * width + x;
      Vec3& pixel = image.pixels[index];
      if (index % 37 == 0) {
        // Sparse specular highlights, still deterministic.
        const double streak = 1.0 + 0.15 * std::sin(u * 40.0);
        pixel = {streak, streak, streak};
      } else if (index % 11 == 0) {
        // Skin-like patches with a slight red bias.
        pixel = {0.82 - 0.10 * v, 0.60 - 0.08 * u, 0.48 - 0.05 * v};
      } else {
        // Ramp weave: each channel driven by a different combination keeps a
        // channel swap from looking plausible.
        pixel = {u, v, 0.5 + 0.5 * std::sin((u - v) * 6.283185307179586)};
      }
      // Out-of-range values exercise domain clamping; they are intentional.
      if (index % 53 == 0) pixel.r = -0.05;
      if (index % 59 == 0) pixel.g = 1.15;
    }
  }
  return image;
}

void write_fixture_image(const std::string& path, const Image& image) {
  const std::string payload = encode_ppm(image);
  std::ofstream out(path, std::ios::binary | std::ios::trunc);
  if (!out) {
    fail(ExitCode::Output, path + ": cannot create fixture image");
  }
  out.write(payload.data(), static_cast<std::streamsize>(payload.size()));
  out.flush();
  if (!out) {
    fail(ExitCode::Output, path + ": write failure");
  }
}

bool ensure_directory(const std::string& path) {
  std::error_code error;
  const bool created = std::filesystem::create_directories(path, error);
  if (error) {
    fail(ExitCode::Output, path + ": cannot create directory: " +
                                error.message());
  }
  (void)created;
  return std::filesystem::is_directory(path, error) && !error;
}

std::string join_path(const std::string& directory, const std::string& name) {
  if (directory.empty()) return name;
  if (directory.back() == '/') return directory + name;
  return directory + "/" + name;
}

